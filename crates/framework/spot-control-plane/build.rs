//! Generates the module registry: one `pub mod` per `src/modules/*.rs` file (not `mod.rs`) and a
//! `REGISTRY` table of the modules that declare `pub const ORDER: u32` and
//! `pub fn register(ctx: &mut CpCtx) -> Result<(), CpError>`. The same technique as the services
//! registry of `spot-cli` (WP-PRD-01.T26): a module is one new file and edits nothing shared.
//! Std only.

use std::path::{Path, PathBuf};

fn valid_module_name(name: &str) -> bool {
    let mut chars = name.chars();
    let Some(first) = chars.next() else {
        return false;
    };
    (first.is_ascii_lowercase() || first == '_')
        && chars.all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '_')
        && !matches!(
            name,
            "self" | "super" | "crate" | "mod" | "fn" | "pub" | "use" | "type" | "as"
        )
}

fn scan(dir: &Path) -> Result<Vec<(String, bool)>, String> {
    let mut files: Vec<PathBuf> = Vec::new();
    let entries = std::fs::read_dir(dir).map_err(|e| format!("{}: {e}", dir.display()))?;
    for entry in entries {
        let path = entry.map_err(|e| e.to_string())?.path();
        if path.extension().and_then(|e| e.to_str()) == Some("rs") {
            files.push(path);
        }
    }
    files.sort();
    let mut modules = Vec::new();
    for path in files {
        let file_name = path
            .file_name()
            .and_then(|n| n.to_str())
            .ok_or_else(|| format!("{}: not a UTF-8 file name", path.display()))?
            .to_owned();
        if file_name == "mod.rs" {
            continue;
        }
        let stem = file_name.trim_end_matches(".rs").to_owned();
        if !valid_module_name(&stem) {
            return Err(format!("src/modules/{file_name}: not a valid module name"));
        }
        let source =
            std::fs::read_to_string(&path).map_err(|e| format!("src/modules/{file_name}: {e}"))?;
        let has_order = source
            .lines()
            .any(|l| l.starts_with("pub const ORDER: u32"));
        let registers = source.lines().any(|l| l.starts_with("pub fn register("));
        if has_order != registers {
            return Err(format!(
                "src/modules/{file_name}: declare both `pub const ORDER: u32` and `pub fn register(`, or neither"
            ));
        }
        modules.push((stem, registers));
    }
    Ok(modules)
}

fn main() {
    let manifest = std::env::var("CARGO_MANIFEST_DIR")
        .unwrap_or_default()
        .replace('\\', "/");
    let out_dir = std::env::var("OUT_DIR").unwrap_or_default();
    println!("cargo:rerun-if-changed=src/modules");
    let dir = Path::new(&manifest).join("src/modules");
    let modules = match scan(&dir) {
        Ok(modules) => modules,
        Err(message) => {
            eprintln!("error: {message}");
            std::process::exit(1);
        }
    };
    let mut out = String::from("// @generated by build.rs from src/modules/*.rs. Do not edit.\n");
    for (name, _) in &modules {
        out.push_str(&format!(
            "#[path = \"{manifest}/src/modules/{name}.rs\"]\npub mod {name};\n"
        ));
    }
    out.push_str("/// Every module that registers itself, in file-name order.\n");
    out.push_str("pub const REGISTRY: &[Registration] = &[\n");
    for (name, registers) in &modules {
        if *registers {
            out.push_str(&format!(
                "    Registration {{ name: \"{name}\", order: {name}::ORDER, register: {name}::register }},\n"
            ));
        }
    }
    out.push_str("];\n");
    let target = Path::new(&out_dir).join("modules_registry.rs");
    if let Err(error) = std::fs::write(&target, out) {
        eprintln!("error: {}: {error}", target.display());
        std::process::exit(1);
    }
}
