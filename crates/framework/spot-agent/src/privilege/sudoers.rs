//! The sudoers drop-in generator (`spot-agent-priv --print-sudoers`). The packaging tasks
//! install the output; this crate only generates it.
//!
//! The helper takes its parameters on stdin, so every line names the helper and one
//! template exactly: **no wildcard**, no other path, no other argument.

use super::HELPER_PATH;
use super::templates::{TEMPLATES, valid_account_name};

/// Renders the drop-in for the agent account `user`.
///
/// # Errors
/// `Err(())` when `user` is not a valid account name.
#[allow(clippy::result_unit_err)]
pub fn sudoers_dropin(user: &str, helper: &str) -> Result<String, ()> {
    if !valid_account_name(user) || helper != HELPER_PATH {
        return Err(());
    }
    let mut out = String::new();
    out.push_str("# Generated by `spot-agent-priv --print-sudoers`. Do not edit.\n");
    out.push_str("# One exact command per privileged template; the parameters arrive on stdin.\n");
    out.push_str(&format!("Defaults:{user} !requiretty, !visiblepw\n"));
    let names: Vec<String> = TEMPLATES
        .iter()
        .map(|t| format!("{helper} run {}", t.name))
        .collect();
    out.push_str(&format!(
        "Cmnd_Alias SPOT_AGENT_PRIV = \\\n    {}\n",
        names.join(", \\\n    ")
    ));
    out.push_str(&format!("{user} ALL=(root) NOPASSWD: SPOT_AGENT_PRIV\n"));
    Ok(out)
}
