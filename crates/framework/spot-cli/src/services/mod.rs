//! The framework services one `spot serve` process hosts, per site.
//!
//! Every site gets one [`Services`] assembly: the services are *constructed* in the order
//! they are added, *checked* in that order before anything runs (a required service's
//! failure stops the site with a clear message; an optional one's degrades the site), then
//! *run* as tasks driven by the one runtime. Shutdown stops them in the reverse order, each
//! with the assembly's drain deadline, and aborts only what overran it.
//!
//! Two rules the assembly keeps:
//! - a service never outlives the process's shutdown: everything it spawns lives inside its
//!   own [`Service::run`] future, which ends when the stop signal arrives;
//! - state is observable: every transition lands in [`Health`], which the site's
//!   `/api/health/ready` check renders. A stopped optional service keeps the site ready (it
//!   degrades it, so a stopped mail sender must not pull the node out of rotation) and a
//!   stopped required one does not.

