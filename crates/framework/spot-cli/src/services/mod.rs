/// A route reachable without a session, and how often it may be called.
#[derive(Clone, Debug)]
pub struct OpenPath {
    /// The only method that is open.
    pub method: Method,
    /// `/literal/segments` with at most one `{name}` segment. No other wildcard exists.
    pub pattern: &'static str,
    /// The per-site rate limit. There is no unlimited value.
    pub limit: RateLimit,
}

/// How many requests per minute an open path accepts, per site.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct RateLimit {
    /// Requests per clock minute; must be at least 1.
    pub per_minute: u32,
}

/// What happened to one request on an open path.
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum OpenOutcome {
    /// The handler ran and answered with this status.
    Served(u16),
    /// The rate limit refused the request before the handler.
    RateLimited,
}

/// The audit record of one request on an open path: never the concrete path, a body, a header
/// or a credential (a path parameter can be a secret), only the declared pattern.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct OpenRecord {
    /// The site.
    pub site: String,
    /// The module that declared the path.
    pub module: &'static str,
    /// The method.
    pub method: String,
    /// The declared pattern.
    pub pattern: String,
    /// What happened.
    pub outcome: OpenOutcome,
    /// Seconds since the Unix epoch, from the site clock.
    pub at_unix: i64,
}

/// Where open-path audit records go.
pub trait OpenAudit: Send + Sync {
    /// Records one request. Must not block and must not fail the request.
    fn record(&self, record: &OpenRecord);
}

/// The default sink: one structured `tracing` event per request, target `spot::audit::open_path`.
pub struct TracingOpenAudit;

impl OpenAudit for TracingOpenAudit {
    fn record(&self, record: &OpenRecord) {
        tracing::info!(
            target: "spot::audit::open_path",
            site = %record.site,
            module = record.module,
            method = %record.method,
            pattern = %record.pattern,
            outcome = ?record.outcome,
            at = record.at_unix,
            "open path request"
        );
    }
}

/// A sink that keeps the records in memory (tests, and an operator tool that lists them).
#[derive(Default)]
pub struct MemoryOpenAudit(Mutex<Vec<OpenRecord>>);

impl MemoryOpenAudit {
    /// The records so far.
    pub fn records(&self) -> Vec<OpenRecord> {
        self.0.lock().unwrap_or_else(|p| p.into_inner()).clone()
    }
}

impl OpenAudit for MemoryOpenAudit {
    fn record(&self, record: &OpenRecord) {
        self.0
            .lock()
            .unwrap_or_else(|p| p.into_inner())
            .push(record.clone());
    }
}

#[derive(Clone, Debug, PartialEq, Eq)]
enum Segment {
    Literal(String),
    Param,
}

struct OpenEntry {
    module: &'static str,
    method: Method,
    pattern: &'static str,
    segments: Vec<Segment>,
    per_minute: u32,
}

impl OpenEntry {
    fn shape(&self) -> String {
        let mut out = String::new();
        for s in &self.segments {
            out.push('/');
            match s {
                Segment::Literal(l) => out.push_str(l),
                Segment::Param => out.push_str("{}"),
            }
        }
        out
    }
    fn params(&self) -> usize {
        self.segments
            .iter()
            .filter(|s| matches!(s, Segment::Param))
            .count()
    }
    fn matches(&self, method: &Method, path: &str) -> bool {
        if *method != self.method {
            return false;
        }
        let Some(rest) = path.strip_prefix('/') else {
            return false;
        };
        let parts: Vec<&str> = rest.split('/').collect();
        parts.len() == self.segments.len()
            && parts
                .iter()
                .zip(&self.segments)
                .all(|(part, segment)| match segment {
                    Segment::Literal(l) => part == l,
                    Segment::Param => !part.is_empty(),
                })
    }
}

/// Paths the host owns and an open path may never shadow.
fn reserved(shape: &str) -> bool {
    shape == "/metrics"
        || shape == "/api/v1/realtime"
        || shape == "/api/v1/auth"
        || shape.starts_with("/api/v1/auth/")
        || shape == crate::gate::PASSWORD_PATH
        || shape.starts_with("/api/health")
}

fn parse_pattern(pattern: &str) -> Result<Vec<Segment>, String> {
    let Some(rest) = pattern.strip_prefix('/') else {
        return Err("the pattern must start with `/`".into());
    };
    if rest.is_empty() {
        return Err("the pattern must name at least one segment".into());
    }
    let mut segments = Vec::new();
    for part in rest.split('/') {
        if part.is_empty() {
            return Err("the pattern has an empty segment".into());
        }
        if let Some(inner) = part.strip_prefix('{') {
            let name = inner.strip_suffix('}').unwrap_or("");
            let ok = !name.is_empty()
                && name
                    .chars()
                    .all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '_')
                && !name.starts_with(|c: char| c.is_ascii_digit());
            if !ok {
                return Err("a `{name}` segment needs a lowercase identifier".into());
            }
            segments.push(Segment::Param);
        } else if part.contains(['{', '}', '*', '?', '#']) {
            return Err("only a whole `{name}` segment is a parameter; no other wildcard".into());
        } else {
            segments.push(Segment::Literal(part.to_owned()));
        }
    }
    if segments
        .iter()
        .filter(|s| matches!(s, Segment::Param))
        .count()
        > 1
    {
        return Err("at most one path parameter".into());
    }
    Ok(segments)
}

/// The allow-list of routes reachable without a session, with the rate limit and audit that
/// guard them. Built once per site; the host asks it before it authenticates.
pub struct OpenPaths {
    site: String,
    entries: Vec<OpenEntry>,
    windows: Mutex<Vec<(i64, u32)>>,
    clock: Arc<dyn Clock>,
    audit: Arc<dyn OpenAudit>,
}

impl OpenPaths {
    /// No open path at all (the default of a site whose modules declared none).
    pub fn none(site: &str, clock: Arc<dyn Clock>) -> Self {
        Self {
            site: site.to_owned(),
            entries: Vec::new(),
            windows: Mutex::new(Vec::new()),
            clock,
            audit: Arc::new(TracingOpenAudit),
        }
    }

    /// Replaces the audit sink.
    pub fn with_audit(mut self, audit: Arc<dyn OpenAudit>) -> Self {
        self.audit = audit;
        self
    }

    /// `"METHOD pattern (module)"` for every declared path, sorted.
    pub fn listing(&self) -> Vec<String> {
        let mut out: Vec<String> = self
            .entries
            .iter()
            .map(|e| format!("{} {} ({})", e.method, e.pattern, e.module))
            .collect();
        out.sort();
        out
    }

    /// The index of the most specific entry (fewest parameters) that matches, if any.
    fn find(&self, method: &Method, path: &str) -> Option<usize> {
        // A pattern with a `{param}` segment can overlap a path the host owns (`/metrics`, the
        // realtime upgrade, the auth routes, health, the password path): those are never open,
        // whatever an entry declares, so they always take the authenticate-first rule.
        if reserved(path) {
            return None;
        }
        self.entries
            .iter()
            .enumerate()
            .filter(|(_, e)| e.matches(method, path))
            .min_by_key(|(i, e)| (e.params(), *i))
            .map(|(i, _)| i)
    }

    /// Takes one request from entry `index`'s budget for the current clock minute.
    fn admit(&self, index: usize) -> (bool, i64) {
        let now = self.clock.now_utc().unix_timestamp();
        let minute = now.div_euclid(60);
        let mut windows = self.windows.lock().unwrap_or_else(|p| p.into_inner());
        let Some(slot) = windows.get_mut(index) else {
            return (false, now);
        };
        if slot.0 != minute {
            *slot = (minute, 0);
        }
        let limit = self.entries.get(index).map_or(0, |e| e.per_minute);
        if slot.1 >= limit {
            return (false, now);
        }
        slot.1 += 1;
        (true, now)
    }

    /// Serves `request` on an open path, or hands it back untouched (`Err`) when no declared
    /// method and pattern matches, so the host goes on with its authenticate-first rule.
    ///
    /// A matching request is rate limited before the handler runs (429 with `Retry-After`),
    /// audited either way, and routed through `router` without a principal.
    pub async fn serve(&self, request: Request, router: &Router) -> Result<Response, Box<Request>> {
        let Some(index) = self.find(request.method(), request.uri().path()) else {
            return Err(Box::new(request));
        };
        let Some(entry) = self.entries.get(index) else {
            return Err(Box::new(request));
        };
        let (admitted, now) = self.admit(index);
        let record = |outcome: OpenOutcome| OpenRecord {
            site: self.site.clone(),
            module: entry.module,
            method: entry.method.to_string(),
            pattern: entry.pattern.to_owned(),
            outcome,
            at_unix: now,
        };
        if !admitted {
            self.audit.record(&record(OpenOutcome::RateLimited));
            let retry = 60 - now.rem_euclid(60);
            let mut response = (
                StatusCode::TOO_MANY_REQUESTS,
                [(header::CONTENT_TYPE, "application/json")],
                r#"{"error":{"code":"rate_limited"}}"#,
            )
                .into_response();
            if let Ok(value) = HeaderValue::from_str(&retry.to_string()) {
                response.headers_mut().insert(header::RETRY_AFTER, value);
            }
            return Ok(response);
        }
        let response = match router.clone().oneshot(request).await {
            Ok(response) => response,
            Err(never) => match never {},
        };
        self.audit
            .record(&record(OpenOutcome::Served(response.status().as_u16())));
        Ok(response)
    }
}

/// What a finished registration hands the host.
pub struct Assembled {
    /// The services in start order; `None` for a rebuild that keeps the running ones.
    pub assembly: Option<Services>,
    /// The site router with every module's edits applied.
    pub router: Router,
    /// The routes open without a session.
    pub open: Arc<OpenPaths>,
}

/// One site's registration context: everything a module may take from the site, and everything
/// it may contribute. Built once per site build; it holds no process-wide state, so a module
/// cannot see another site.
pub struct SiteCtx<'a> {
    env: Option<SiteEnv<'a>>,
    label: String,
    grace: Duration,
    clock: Arc<dyn Clock>,
    settings: BTreeMap<String, toml::Value>,
    assembling: bool,
    module: &'static str,
    order: u32,
    services: Vec<(u32, usize, Arc<dyn Service>)>,
    ports: HashMap<TypeId, PortEntry>,
    edits: Vec<RouterEdit>,
    open: Vec<OpenEntry>,
    open_audit: Arc<dyn OpenAudit>,
    finalisers: Vec<(u32, &'static str, Finaliser)>,
    handlers: Option<spot_jobs::worker::JobHandlerRegistry>,
}

impl<'a> SiteCtx<'a> {
    /// A context for the site called `label`.
    ///
    /// `assembling` is `true` for the first build (the services are created and started) and
    /// `false` for a reload (the running services stay; a module still declares its routes and
    /// open paths, and must not build a second copy of a service).
    pub fn new(
        label: impl Into<String>,
        grace: Duration,
        clock: Arc<dyn Clock>,
        settings: BTreeMap<String, toml::Value>,
        assembling: bool,
    ) -> Self {
        Self {
            env: None,
            label: label.into(),
            grace,
            clock,
            settings,
            assembling,
            module: "host",
            order: 0,
            services: Vec::new(),
            ports: HashMap::new(),
            edits: Vec::new(),
            open: Vec::new(),
            open_audit: Arc::new(TracingOpenAudit),
            finalisers: Vec::new(),
            handlers: Some(spot_jobs::worker::JobHandlerRegistry::new()),
        }
    }

    /// Attaches the site (root, configuration, database, permissions, live hub).
    pub fn with_env(mut self, env: SiteEnv<'a>) -> Self {
        self.env = Some(env);
        self
    }

    /// Replaces the open-path audit sink.
    pub fn with_open_audit(mut self, audit: Arc<dyn OpenAudit>) -> Self {
        self.open_audit = audit;
        self
    }

    fn enter(&mut self, module: &'static str, order: u32) {
        self.module = module;
        self.order = order;
    }

    /// Names the module the next calls belong to (the host uses it for what it provides itself).
    pub fn as_module(&mut self, module: &'static str, order: u32) {
        self.enter(module, order);
    }

    /// The module being registered.
    pub fn module(&self) -> &'static str {
        self.module
    }

    /// The site name.
    pub fn label(&self) -> &str {
        &self.label
    }

    /// The site clock: the only source of `now` a module reads.
    pub fn clock(&self) -> &Arc<dyn Clock> {
        &self.clock
    }

    /// Whether this build creates the services. `false` on a reload.
    pub fn assembling(&self) -> bool {
        self.assembling
    }

    /// The site, or an error naming the module when the context carries none.
    pub fn env(&self) -> crate::Result<&SiteEnv<'a>> {
        self.env.as_ref().ok_or_else(|| {
            Error(format!(
                "module `{}` needs the site, which this context does not carry",
                self.module
            ))
        })
    }

    /// Adds a service, placed at the current module's `ORDER` (insertion order breaks ties).
    /// Nothing is added on a reload build.
    pub fn add(&mut self, service: Arc<dyn Service>) {
        if self.assembling {
            let seq = self.services.len();
            self.services.push((self.order, seq, service));
        }
    }

    /// Provides `port` to the modules that start after this one. Providing the same type twice
    /// is an error naming both modules.
    pub fn provide<T: ?Sized + Send + Sync + 'static>(
        &mut self,
        port: Arc<T>,
    ) -> crate::Result<()> {
        let key = TypeId::of::<Arc<T>>();
        let name = std::any::type_name::<T>();
        if let Some(existing) = self.ports.get(&key) {
            return Err(Error(format!(
                "the port `{name}` is provided by module `{}` and again by module `{}`",
                existing.module, self.module
            )));
        }
        self.ports.insert(
            key,
            PortEntry {
                module: self.module,
                port: name,
                value: Box::new(port),
            },
        );
        Ok(())
    }

    /// The port of type `T` if a module provided it.
    pub fn port<T: ?Sized + Send + Sync + 'static>(&self) -> Option<Arc<T>> {
        self.ports
            .get(&TypeId::of::<Arc<T>>())
            .and_then(|e| e.value.downcast_ref::<Arc<T>>())
            .cloned()
    }

    /// The port of type `T`, or an error naming this module and the port: the provider must
    /// have a smaller `ORDER`.
    pub fn require_port<T: ?Sized + Send + Sync + 'static>(&self) -> crate::Result<Arc<T>> {
        self.port::<T>().ok_or_else(|| {
            Error(format!(
                "module `{}` requires the port `{}`, which no module registered before it provides",
                self.module,
                std::any::type_name::<T>()
            ))
        })
    }

    /// The ports provided so far, as `(module, port type)`, for an operator listing.
    pub fn ports(&self) -> Vec<(&'static str, &'static str)> {
        let mut out: Vec<_> = self.ports.values().map(|e| (e.module, e.port)).collect();
        out.sort_unstable();
        out
    }

    /// Edits the site router (add routes, add a layer). Applied in registration order, before
    /// the telemetry layer, so what a module adds is counted and logged like any route.
    pub fn router_layer(&mut self, edit: impl FnOnce(Router) -> Router + Send + 'static) {
        self.edits.push(Box::new(edit));
    }

    /// Queues `work` to run after every module registered. A service it adds is placed at this
    /// module's `ORDER`.
    pub fn finally(
        &mut self,
        work: impl FnOnce(&mut SiteCtx<'_>) -> crate::Result<()> + Send + 'static,
    ) {
        self.finalisers
            .push((self.order, self.module, Box::new(work)));
    }

    /// The job handlers modules contribute; the jobs module takes them in its finaliser.
    pub fn job_handlers(&mut self) -> &mut spot_jobs::worker::JobHandlerRegistry {
        self.handlers
            .get_or_insert_with(spot_jobs::worker::JobHandlerRegistry::new)
    }

    /// Takes the job handlers (the jobs module, once every module contributed).
    pub fn take_job_handlers(&mut self) -> spot_jobs::worker::JobHandlerRegistry {
        self.handlers.take().unwrap_or_default()
    }

    /// Declares routes reachable without a session. Every other path keeps the
    /// authenticate-first rule. A malformed pattern, a reserved path, a zero limit or a method
    /// and pattern another module already declared is an error that stops the site start.
    pub fn open_paths(&mut self, paths: &[OpenPath]) -> crate::Result<()> {
        for path in paths {
            let segments = parse_pattern(path.pattern).map_err(|why| {
                Error(format!(
                    "module `{}` declares the open path `{} {}`: {why}",
                    self.module, path.method, path.pattern
                ))
            })?;
            if path.limit.per_minute == 0 {
                return Err(Error(format!(
                    "module `{}` declares the open path `{} {}` with a rate limit of 0 per minute",
                    self.module, path.method, path.pattern
                )));
            }
            let entry = OpenEntry {
                module: self.module,
                method: path.method.clone(),
                pattern: path.pattern,
                segments,
                per_minute: path.limit.per_minute,
            };
            if reserved(&entry.shape()) {
                return Err(Error(format!(
                    "module `{}` declares the open path `{} {}`, which the host reserves",
                    self.module, path.method, path.pattern
                )));
            }
            if let Some(other) = self
                .open
                .iter()
                .find(|o| o.method == entry.method && o.shape() == entry.shape())
            {
                return Err(Error(format!(
                    "the open path `{} {}` is declared by module `{}` and again by module `{}`",
                    entry.method, entry.pattern, other.module, entry.module
                )));
            }
            self.open.push(entry);
        }
        Ok(())
    }

    /// A typed settings table: `[services.<name>]` of a module the typed configuration does not
    /// know. `T` should carry `deny_unknown_fields`. An absent table is an error; a module with
    /// optional settings asks [`SiteCtx::settings_or_default`].
    ///
    /// An error names the table and, when it can tell, the key; it never echoes a value (a table
    /// may hold a secret reference).
    pub fn settings<T: DeserializeOwned>(&self, name: &str) -> crate::Result<T> {
        match self.settings.get(name) {
            Some(table) => decode_settings(name, table),
            None => Err(Error(format!("services.{name} is not configured"))),
        }
    }

    /// Like [`SiteCtx::settings`], and `T::default()` when the table is absent.
    pub fn settings_or_default<T: DeserializeOwned + Default>(
        &self,
        name: &str,
    ) -> crate::Result<T> {
        match self.settings.get(name) {
            Some(table) => decode_settings(name, table),
            None => Ok(T::default()),
        }
    }

    fn run_finalisers(&mut self) -> crate::Result<()> {
        let mut work = std::mem::take(&mut self.finalisers);
        work.sort_by(|a, b| a.0.cmp(&b.0).then(a.1.cmp(b.1)));
        for (order, module, run) in work {
            self.enter(module, order);
            run(self).map_err(|e| {
                Error(format!(
                    "services registry: module `{module}` failed to finish registering: {e}"
                ))
            })?;
        }
        Ok(())
    }

    /// Ends registration: builds the assembly, applies the router edits and freezes the open
    /// paths. Services are added to the assembly in `(ORDER, registration)` order.
    pub fn finish(mut self, router: Router) -> Assembled {
        let mut router = router;
        for edit in std::mem::take(&mut self.edits) {
            router = edit(router);
        }
        let mut open = std::mem::take(&mut self.open);
        // The most specific entry wins in `find`; keep declaration order otherwise.
        open.sort_by_key(|e| e.params());
        let windows = vec![(i64::MIN, 0); open.len()];
        let paths = OpenPaths {
            site: self.label.clone(),
            entries: open,
            windows: Mutex::new(windows),
            clock: self.clock.clone(),
            audit: self.open_audit.clone(),
        };
        let assembly = if self.assembling {
            let mut assembly = Services::new(self.label.clone(), self.grace);
            let mut services = std::mem::take(&mut self.services);
            services.sort_by_key(|(order, seq, _)| (*order, *seq));
            for (_, _, service) in services {
                assembly.add(service);
            }
            assembly.health().set_open_paths(paths.listing());
            Some(assembly)
        } else {
            None
        };
        Assembled {
            assembly,
            router,
            open: Arc::new(paths),
        }
    }
}

/// Deserialises one settings table without echoing a value.
fn decode_settings<T: DeserializeOwned>(name: &str, table: &toml::Value) -> crate::Result<T> {
    match table.clone().try_into::<T>() {
        Ok(value) => Ok(value),
        Err(e) => {
            let message = e.message();
            // `unknown field` and `missing field` quote only key names. Any other serde message
            // can quote the offending value, so it is replaced by a fixed phrase.
            if message.starts_with("unknown field") || message.starts_with("missing field") {
                return Err(Error(format!("services.{name}: {message}")));
            }
            let key = table.as_table().and_then(|t| {
                t.keys()
                    .find(|k| {
                        let mut rest = t.clone();
                        rest.remove(k.as_str());
                        match toml::Value::Table(rest).try_into::<T>() {
                            Ok(_) => true,
                            Err(other) => {
                                let m = other.message();
                                !(m.starts_with("invalid type") || m.starts_with("invalid value"))
                            }
                        }
                    })
                    .cloned()
            });
            Err(Error(match key {
                Some(key) => format!("services.{name}.{key}: wrong type or an invalid value"),
                None => format!("services.{name}: invalid settings"),
            }))
        }
    }
}

#[cfg(test)]
#[allow(clippy::expect_used)]
mod registry_tests {
    use super::*;

    #[test]
    fn generated_table_is_sorted_with_unique_names() {
        let table = ordered(&[REGISTRY]).expect("the generated table orders");
        let mut seen = std::collections::BTreeSet::new();
        for r in &table {
            assert!(seen.insert(r.name), "module {} registered twice", r.name);
        }
        for pair in table.windows(2) {
            assert!(
                (pair[0].order, pair[0].name) < (pair[1].order, pair[1].name),
                "{} and {} are not in start order",
                pair[0].name,
                pair[1].name
            );
        }
        for r in REGISTRY {
            assert!(
                r.order >= 1000,
                "{} must use an ORDER of 1000 or more",
                r.name
            );
        }
    }

    #[test]
    fn a_module_with_a_role_condition_starts_after_node_role() {
        for condition in ROLE_CONDITIONS {
            let order = REGISTRY
                .iter()
                .find(|r| r.name == condition.name)
                .map(|r| r.order)
                .expect("a condition names a registered module");
            assert!(
                order > node_role::ORDER,
                "{} declares ROLES but its ORDER {order} is not above node_role's {}",
                condition.name,
                node_role::ORDER
            );
            for role in condition.roles {
                assert!(
                    node_role::Role::parse(role).is_ok(),
                    "{} names the role `{role}`, which is not a role",
                    condition.name
                );
            }
        }
    }

    #[test]
    fn the_table_of_roles_matches_the_modules_that_exist() {
        let existing: Vec<&str> = REGISTRY.iter().map(|r| r.name).collect();
        for row in node_role::SERVICE_SETS {
            if !existing.contains(&row.module) {
                continue; // a service of WP-RTB-02 not in the tree yet: data only
            }
            let condition = ROLE_CONDITIONS.iter().find(|c| c.name == row.module);
            let condition = condition.unwrap_or_else(|| {
                panic!("{} is in SERVICE_SETS but declares no ROLES", row.module)
            });
            assert_eq!(
                condition.roles, row.roles,
                "{} ROLES differ from its row",
                row.module
            );
        }
        for condition in ROLE_CONDITIONS {
            assert!(
                node_role::SERVICE_SETS
                    .iter()
                    .any(|r| r.module == condition.name),
                "{} declares ROLES but has no row in SERVICE_SETS",
                condition.name
            );
        }
    }

    #[test]
    fn patterns() {
        assert!(parse_pattern("/api/v1/process/hook/{trigger}").is_ok());
        assert!(parse_pattern("api/x").is_err());
        assert!(parse_pattern("/a/{x}/{y}").is_err());
        assert!(parse_pattern("/a/*").is_err());
        assert!(parse_pattern("/a/pre{x}").is_err());
        assert!(parse_pattern("/a//b").is_err());
        assert!(parse_pattern("/").is_err());
    }
}
