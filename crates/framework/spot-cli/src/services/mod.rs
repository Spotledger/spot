/// A service with no loop of its own: storage and authentication exist before the assembly
/// starts, so their task only waits for the stop signal and their check is the real work.
pub struct Idle {
    name: &'static str,
    level: Level,
    check: Arc<dyn Fn() -> CheckFuture<'static> + Send + Sync>,
}

impl Idle {
    /// A static service called `name`, at `level`, checked by `check`.
    pub fn new(
        name: &'static str,
        level: Level,
        check: impl Fn() -> CheckFuture<'static> + Send + Sync + 'static,
    ) -> Arc<Self> {
        Arc::new(Self {
            name,
            level,
            check: Arc::new(check),
        })
    }
}

impl Service for Idle {
    fn name(&self) -> &'static str {
        self.name
    }
    fn level(&self) -> Level {
        self.level
    }
    fn check(&self) -> CheckFuture<'_> {
        (self.check)()
    }
    fn run(&self, stop: watch::Receiver<bool>) -> RunFuture<'_> {
        Box::pin(async move {
            let mut stop = stop;
            let _ = stop.changed().await;
            Ok(())
        })
    }
}

/// Whether losing this service stops the site or only degrades it.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Level {
    /// Storage, metadata, authentication, jobs, the coordinator: the site cannot serve.
    Required,
    /// Mail and print: the site serves and says it is degraded.
    Optional,
}

impl Level {
    /// The word readiness uses for this level.
    pub fn as_str(self) -> &'static str {
        match self {
            Level::Required => "required",
            Level::Optional => "optional",
        }
    }
}

/// A service check's answer: `Ok(())`, or why it cannot serve.
pub type CheckFuture<'a> = Pin<Box<dyn Future<Output = Result<(), String>> + Send + 'a>>;

/// A service task's answer: `Ok(())` on a clean stop, `Err` with the reason it stopped.
pub type RunFuture<'a> = Pin<Box<dyn Future<Output = Result<(), String>> + Send + 'a>>;

/// One framework service hosted by `spot serve`.
pub trait Service: Send + Sync {
    /// The stable name readiness and logs use.
    fn name(&self) -> &'static str;
    /// Whether losing it stops the site.
    fn level(&self) -> Level;
    /// The start-up health check: it must fail with a message an operator can act on.
    fn check(&self) -> CheckFuture<'_>;
    /// The task the one runtime drives. It must return once `stop` is set to `true`.
    fn run(&self, stop: watch::Receiver<bool>) -> RunFuture<'_>;
    /// Drains after `run` returned: release a lease, flush a queue. Called in reverse start
    /// order with the assembly's deadline.
    fn shutdown(&self) -> RunFuture<'_> {
        Box::pin(async { Ok(()) })
    }
}

/// What a service is doing right now.
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum State {
    /// Constructed, not checked yet.
    Starting,
    /// Checked and running.
    Running,
    /// Stopped, with the reason. An optional service's reason degrades the site.
    Stopped(String),
}

/// Every service's state, shared with the site's readiness check.
#[derive(Clone, Debug, Default)]
pub struct Health(
    Arc<Mutex<BTreeMap<&'static str, (Level, State)>>>,
    Arc<Mutex<Vec<String>>>,
);

impl Health {
    /// An empty registry.
    pub fn new() -> Self {
        Self::default()
    }
    /// Records one service's state.
    pub fn set(&self, name: &'static str, level: Level, state: State) {
        let mut states = self.0.lock().unwrap_or_else(|p| p.into_inner());
        states.insert(name, (level, state));
    }
    /// The recorded states, in name order.
    pub fn states(&self) -> BTreeMap<&'static str, (Level, State)> {
        self.0.lock().unwrap_or_else(|p| p.into_inner()).clone()
    }
    /// Records the open paths of the site (`"METHOD pattern (module)"`), so an operator can see
    /// every route reachable without a session.
    pub fn set_open_paths(&self, paths: Vec<String>) {
        *self.1.lock().unwrap_or_else(|p| p.into_inner()) = paths;
    }
    /// The open paths the site declared, in declaration-sorted order.
    pub fn open_paths(&self) -> Vec<String> {
        self.1.lock().unwrap_or_else(|p| p.into_inner()).clone()
    }
    /// The readiness check that renders this registry for `label` (the site name).
    pub fn check(&self, label: impl Into<String>) -> ServiceHealth {
        ServiceHealth {
            name: label.into(),
            health: self.clone(),
        }
    }
}

/// The `/api/health/ready` check over one site's services.
///
/// A running required service passes. A stopped required service fails the check (the site
/// cannot serve). A stopped optional service passes it with a `degraded:` detail, so a load
/// balancer keeps the site and the operator still sees what is off.
pub struct ServiceHealth {
    name: String,
    health: Health,
}

impl ReadinessCheck for ServiceHealth {
    fn name(&self) -> &str {
        &self.name
    }

    fn check(&self) -> Pin<Box<dyn Future<Output = CheckResult> + Send + '_>> {
        let states = self.health.states();
        Box::pin(async move {
            let mut degraded = Vec::new();
            for (name, (level, state)) in &states {
                match (level, state) {
                    (_, State::Running) => {}
                    (Level::Required, State::Starting) => {
                        return CheckResult::failed(format!(
                            "required service `{name}` has not finished starting"
                        ));
                    }
                    (Level::Required, State::Stopped(reason)) => {
                        return CheckResult::failed(format!(
                            "required service `{name}` is stopped: {reason}"
                        ));
                    }
                    (Level::Optional, State::Starting) => {
                        degraded.push(format!("{name} (starting)"))
                    }
                    (Level::Optional, State::Stopped(reason)) => {
                        degraded.push(format!("{name} ({reason})"));
                    }
                }
            }
            if degraded.is_empty() {
                CheckResult::ok()
            } else {
                CheckResult {
                    ok: true,
                    detail: format!("degraded: {}", degraded.join(", ")),
                }
            }
        })
    }
}

/// One site's service assembly.
pub struct Services {
    label: String,
    health: Health,
    services: Vec<Arc<dyn Service>>,
    stop: watch::Sender<bool>,
    tasks: Vec<(&'static str, JoinHandle<()>)>,
    grace: Duration,
}

impl Services {
    /// An empty assembly for the site called `label`, stopping each service within `grace`.
    pub fn new(label: impl Into<String>, grace: Duration) -> Self {
        let (stop, _) = watch::channel(false);
        Self {
            label: label.into(),
            health: Health::new(),
            services: Vec::new(),
            stop,
            tasks: Vec::new(),
            grace,
        }
    }

    /// The site this assembly serves.
    pub fn label(&self) -> &str {
        &self.label
    }

    /// Adds a service. The order of `add` calls is the construction and start order; shutdown
    /// runs in the reverse order.
    pub fn add(&mut self, service: Arc<dyn Service>) -> &mut Self {
        self.health
            .set(service.name(), service.level(), State::Starting);
        self.services.push(service);
        self
    }

    /// The services, in start order.
    pub fn services(&self) -> &[Arc<dyn Service>] {
        &self.services
    }

    /// The site's readiness check.
    pub fn health_check(&self) -> ServiceHealth {
        self.health.check(self.label.clone())
    }

    /// The shared state registry (for tests and logs).
    pub fn health(&self) -> &Health {
        &self.health
    }

    /// Checks every service in start order, then starts the healthy ones.
    ///
    /// A required failure returns the error the site's start reports, without starting
    /// anything: a half-started site is worse than a refused one. An optional failure records
    /// a degradation and leaves that service unstarted.
    pub async fn start(&mut self) -> Result<(), String> {
        let mut degradations = Vec::new();
        for service in &self.services {
            tracing::debug!(service = service.name(), site = %self.label, "checking service");
            match service.check().await {
                Ok(()) => self
                    .health
                    .set(service.name(), service.level(), State::Starting),
                Err(reason) => match service.level() {
                    Level::Required => {
                        self.health.set(
                            service.name(),
                            service.level(),
                            State::Stopped(reason.clone()),
                        );
                        return Err(format!(
                            "site `{}`: required service `{}` failed its start-up check: {reason}",
                            self.label,
                            service.name()
                        ));
                    }
                    Level::Optional => {
                        tracing::warn!(
                            service = service.name(),
                            site = %self.label,
                            %reason,
                            "optional service degraded the site"
                        );
                        self.health.set(
                            service.name(),
                            service.level(),
                            State::Stopped(reason.clone()),
                        );
                        degradations.push(format!("{} ({reason})", service.name()));
                    }
                },
            }
        }
        for service in &self.services {
            if !matches!(
                self.health
                    .states()
                    .get(service.name())
                    .map(|(_, state)| state.clone()),
                Some(State::Starting)
            ) {
                continue;
            }
            let service = Arc::clone(service);
            let stop = self.stop.subscribe();
            let health = self.health.clone();
            let name = service.name();
            let level = service.level();
            health.set(name, level, State::Running);
            let task = tokio::spawn(async move {
                match service.run(stop).await {
                    Ok(()) => health.set(name, level, State::Stopped("stopped".into())),
                    Err(reason) => {
                        tracing::error!(service = name, %reason, "service stopped with an error");
                        health.set(name, level, State::Stopped(reason));
                    }
                }
            });
            self.tasks.push((name, task));
        }
        if !degradations.is_empty() {
            tracing::warn!(
                site = %self.label,
                degraded = %degradations.join(", "),
                "site started degraded"
            );
        }
        Ok(())
    }

    /// Stops every started service in the reverse order: signal, wait up to the grace period
    /// for each task, then drain it. A task that overruns is aborted, never leaked.
    pub async fn shutdown(&mut self) {
        let _ = self.stop.send(true);
        let grace = self.grace;
        let mut tasks = std::mem::take(&mut self.tasks);
        while let Some((name, mut task)) = tasks.pop() {
            match tokio::time::timeout(grace, &mut task).await {
                Ok(Ok(())) => {}
                Ok(Err(join)) => {
                    tracing::warn!(service = name, error = %join, "service task failed");
                }
                Err(_) => {
                    // A task that overran the deadline is aborted, never left running.
                    task.abort();
                    tracing::warn!(
                        service = name,
                        "service did not stop within the grace period"
                    );
                }
            }
        }
        for service in self.services.iter().rev() {
            match tokio::time::timeout(grace, service.shutdown()).await {
                Ok(Ok(())) => {}
                Ok(Err(reason)) => {
                    tracing::warn!(
                        service = service.name(),
                        %reason,
                        "service drain reported a problem"
                    );
                }
                Err(_) => tracing::warn!(
                    service = service.name(),
                    "service drain did not finish within the grace period"
                ),
            }
            if let Some((_, State::Running)) = self.health.states().get(service.name()) {
                self.health.set(
                    service.name(),
                    service.level(),
                    State::Stopped("stopped".into()),
                );
            }
        }
    }
}

