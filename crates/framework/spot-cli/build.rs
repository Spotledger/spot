//! Generates two registries.
//!
//! Services: one `pub mod` per `src/services/*.rs` file (not `mod.rs`) and a `REGISTRY` table of
//! the modules that declare `ORDER` and `register`.
//!
//! Commands: one `pub mod` per `src/commands/*.rs` file (not `mod.rs`) and a `COMMANDS` table of
//! the modules that declare `NAME`, `command` and `run`. A duplicate name, or a name equal to a
//! built-in derive command of `src/main.rs`, stops the build naming both files.
//!
//! The scanner is plain functions over names and source text, so `tests/registry.rs` includes
//! this file and tests them without a build. Std only: no dependency.

use std::path::{Path, PathBuf};

/// What the scanner found in one module file.
#[derive(Debug, PartialEq, Eq)]
#[allow(dead_code)]
pub struct Module {
    /// The module (file stem), a valid Rust identifier.
    pub name: String,
    /// The file, relative to the manifest directory, with forward slashes.
    pub path: String,
    /// `register` is declared in the file.
    pub registers: bool,
    /// `register` is `async`.
    pub is_async: bool,
}

/// Whether `name` can be a module name: `[a-z_][a-z0-9_]*`, and not a keyword that cannot
/// follow `mod`.
#[allow(dead_code)]
pub fn valid_module_name(name: &str) -> bool {
    let mut chars = name.chars();
    let Some(first) = chars.next() else {
        return false;
    };
    (first.is_ascii_lowercase() || first == '_')
        && chars.all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '_')
        && !matches!(
            name,
            "self" | "super" | "crate" | "mod" | "fn" | "pub" | "use" | "type" | "as"
        )
}

/// Reads one module file's text: does it declare `pub const ORDER: u32` and a top-level
/// `pub fn register` / `pub async fn register`? Only declarations at column 0 count, so an
/// associated function called `register` inside an `impl` makes the file a plain helper.
#[allow(dead_code)]
pub fn inspect(file_name: &str, source: &str) -> Result<(bool, bool), String> {
    let has_order = source
        .lines()
        .any(|l| l.starts_with("pub const ORDER: u32"));
    let sync = source.lines().any(|l| l.starts_with("pub fn register("));
    let asynch = source
        .lines()
        .any(|l| l.starts_with("pub async fn register("));
    if sync && asynch {
        return Err(format!("{file_name}: declares `register` twice"));
    }
    let registers = sync || asynch;
    if registers && !has_order {
        return Err(format!(
            "{file_name}: declares `register` but no `pub const ORDER: u32`"
        ));
    }
    if has_order && !registers {
        return Err(format!(
            "{file_name}: declares `ORDER` but no `pub fn register` (or `pub async fn register`)"
        ));
    }
    Ok((registers, asynch))
}

/// Scans `dir` (the manifest's `src/services`) in file-name order.
#[allow(dead_code)]
pub fn scan(dir: &Path) -> Result<Vec<Module>, String> {
    let mut files: Vec<PathBuf> = Vec::new();
    let entries = std::fs::read_dir(dir).map_err(|e| format!("{}: {e}", dir.display()))?;
    for entry in entries {
        let path = entry.map_err(|e| e.to_string())?.path();
        if path.extension().and_then(|e| e.to_str()) == Some("rs") {
            files.push(path);
        }
    }
    files.sort();
    let mut modules = Vec::new();
    for path in files {
        let file_name = path
            .file_name()
            .and_then(|n| n.to_str())
            .ok_or_else(|| format!("{}: not a UTF-8 file name", path.display()))?
            .to_owned();
        if file_name == "mod.rs" {
            continue;
        }
        let stem = file_name.trim_end_matches(".rs").to_owned();
        if !valid_module_name(&stem) {
            return Err(format!(
                "src/services/{file_name}: the file name is not a valid module name \
                 (lowercase letters, digits and underscores, not starting with a digit)"
            ));
        }
        let source =
            std::fs::read_to_string(&path).map_err(|e| format!("src/services/{file_name}: {e}"))?;
        let (registers, is_async) = inspect(&format!("src/services/{file_name}"), &source)?;
        modules.push(Module {
            path: format!("src/services/{file_name}"),
            name: stem,
            registers,
            is_async,
        });
    }
    Ok(modules)
}

/// The generated source for `modules`; `manifest_dir` is made absolute-with-forward-slashes
/// because `#[path]` needs a literal.
#[allow(dead_code)]
pub fn generate(manifest_dir: &str, modules: &[Module]) -> String {
    let dir = manifest_dir.replace('\\', "/");
    let mut out = String::from("// @generated by build.rs from src/services/*.rs. Do not edit.\n");
    for m in modules {
        out.push_str(&format!(
            "#[path = \"{dir}/{}\"]\npub mod {};\n",
            m.path, m.name
        ));
    }
    for m in modules.iter().filter(|m| m.registers) {
        let name = &m.name;
        if m.is_async {
            out.push_str(&format!(
                "fn __register_{name}<'a, 'b>(ctx: &'a mut SiteCtx<'b>) -> RegisterFuture<'a> {{\n    Box::pin({name}::register(ctx))\n}}\n"
            ));
        } else {
            out.push_str(&format!(
                "fn __register_{name}<'a, 'b>(ctx: &'a mut SiteCtx<'b>) -> RegisterFuture<'a> {{\n    let done = {name}::register(ctx);\n    Box::pin(async move {{ done }})\n}}\n"
            ));
        }
    }
    out.push_str("/// Every module that registers itself, in file-name order.\n");
    out.push_str("pub const REGISTRY: &[Registration] = &[\n");
    for m in modules.iter().filter(|m| m.registers) {
        out.push_str(&format!(
            "    Registration {{ name: \"{0}\", order: {0}::ORDER, register: __register_{0} }},\n",
            m.name
        ));
    }
    out.push_str("];\n");
    out
}

// --- commands ---------------------------------------------------------------------------------

/// What the scanner found in one `src/commands` file.
#[derive(Debug, PartialEq, Eq)]
#[allow(dead_code)]
pub struct CommandModule {
    /// The module (file stem), a valid Rust identifier.
    pub module: String,
    /// The file, relative to the manifest directory, with forward slashes.
    pub path: String,
    /// The command name its `NAME` declares; `None` for a helper file.
    pub name: Option<String>,
}

/// The value of `pub const NAME: &str = "...";` at column 0, if any.
#[allow(dead_code)]
fn command_name_of(source: &str) -> Option<String> {
    let line = source
        .lines()
        .find(|l| l.starts_with("pub const NAME: &str"))?;
    let start = line.find('"')? + 1;
    let end = start + line[start..].find('"')?;
    Some(line[start..end].to_owned())
}

/// Whether `name` can be a subcommand name: lowercase letters, digits and single hyphens, starting
/// with a letter.
#[allow(dead_code)]
pub fn valid_command_name(name: &str) -> bool {
    let mut chars = name.chars();
    let Some(first) = chars.next() else {
        return false;
    };
    first.is_ascii_lowercase()
        && !name.ends_with('-')
        && !name.contains("--")
        && chars.all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '-')
}

/// Reads one command file. A command file declares `pub const NAME: &str`, `pub fn command(` and
/// `pub async fn run(` at column 0, all three or none (none: a helper module). Returns the name.
#[allow(dead_code)]
pub fn inspect_command(file_name: &str, source: &str) -> Result<Option<String>, String> {
    let has = |prefix: &str| source.lines().any(|l| l.starts_with(prefix));
    let items = [
        (has("pub const NAME: &str"), "`pub const NAME: &str`"),
        (has("pub fn command("), "`pub fn command()`"),
        (has("pub async fn run("), "`pub async fn run()`"),
    ];
    if items.iter().all(|(p, _)| *p) {
        let name = command_name_of(source)
            .ok_or_else(|| format!("{file_name}: NAME must be a string literal on one line"))?;
        if !valid_command_name(&name) {
            return Err(format!(
                "{file_name}: the command name `{name}` is not valid (lowercase letters, digits \
                 and single hyphens, starting with a letter)"
            ));
        }
        return Ok(Some(name));
    }
    if items.iter().any(|(p, _)| *p) {
        let missing: Vec<&str> = items.iter().filter(|(p, _)| !p).map(|(_, l)| *l).collect();
        return Err(format!(
            "{file_name}: a command module declares NAME, command and run together; missing {}",
            missing.join(", ")
        ));
    }
    Ok(None)
}

/// The built-in (derive) command names of `src/main.rs`: the variants of `enum Command`,
/// kebab-cased as clap does. Variants are read at four spaces of indentation.
#[allow(dead_code)]
pub fn builtin_commands(main_source: &str) -> Vec<String> {
    let mut names = Vec::new();
    let mut inside = false;
    for line in main_source.lines() {
        if line.starts_with("enum Command") {
            inside = true;
            continue;
        }
        if inside && line.starts_with('}') {
            break;
        }
        if !inside {
            continue;
        }
        let Some(rest) = line.strip_prefix("    ") else {
            continue;
        };
        if !rest.starts_with(|c: char| c.is_ascii_uppercase()) {
            continue;
        }
        let ident: String = rest
            .chars()
            .take_while(|c| c.is_ascii_alphanumeric())
            .collect();
        let mut kebab = String::new();
        for (i, c) in ident.chars().enumerate() {
            if c.is_ascii_uppercase() {
                if i > 0 {
                    kebab.push('-');
                }
                kebab.push(c.to_ascii_lowercase());
            } else {
                kebab.push(c);
            }
        }
        names.push(kebab);
    }
    names
}

/// Fails when two command files declare one name, or a file declares a built-in name. The message
/// names both owners.
#[allow(dead_code)]
pub fn check_command_names(modules: &[CommandModule], builtins: &[String]) -> Result<(), String> {
    let mut seen: Vec<(&str, &str)> = Vec::new();
    for m in modules {
        let Some(name) = m.name.as_deref() else {
            continue;
        };
        if builtins.iter().any(|b| b == name) {
            return Err(format!(
                "{}: the command `{name}` is a built-in command of src/main.rs",
                m.path
            ));
        }
        if let Some((_, other)) = seen.iter().find(|(n, _)| *n == name) {
            return Err(format!(
                "the command `{name}` is declared by both {other} and {}",
                m.path
            ));
        }
        seen.push((name, &m.path));
    }
    Ok(())
}

/// Scans `src/commands` (a missing directory is empty) in file-name order.
#[allow(dead_code)]
pub fn scan_commands(manifest_dir: &Path) -> Result<Vec<CommandModule>, String> {
    let dir = manifest_dir.join("src").join("commands");
    let entries = match std::fs::read_dir(&dir) {
        Ok(entries) => entries,
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => return Ok(Vec::new()),
        Err(e) => return Err(format!("{}: {e}", dir.display())),
    };
    let mut files: Vec<PathBuf> = Vec::new();
    for entry in entries {
        let path = entry.map_err(|e| e.to_string())?.path();
        if path.extension().and_then(|e| e.to_str()) == Some("rs") {
            files.push(path);
        }
    }
    files.sort();
    let mut modules = Vec::new();
    for path in files {
        let file_name = path
            .file_name()
            .and_then(|n| n.to_str())
            .ok_or_else(|| format!("{}: not a UTF-8 file name", path.display()))?
            .to_owned();
        if file_name == "mod.rs" {
            continue;
        }
        let stem = file_name.trim_end_matches(".rs").to_owned();
        let rel = format!("src/commands/{file_name}");
        if !valid_module_name(&stem) {
            return Err(format!(
                "{rel}: the file name is not a valid module name \
                 (lowercase letters, digits and underscores, not starting with a digit)"
            ));
        }
        let source = std::fs::read_to_string(&path).map_err(|e| format!("{rel}: {e}"))?;
        let name = inspect_command(&rel, &source)?;
        modules.push(CommandModule {
            module: stem,
            path: rel,
            name,
        });
    }
    Ok(modules)
}

/// The generated source for the command `modules`.
#[allow(dead_code)]
pub fn generate_commands(manifest_dir: &str, modules: &[CommandModule]) -> String {
    let dir = manifest_dir.replace('\\', "/");
    let mut out = String::from("// @generated by build.rs from src/commands/*.rs. Do not edit.\n");
    for m in modules {
        out.push_str(&format!(
            "#[path = \"{dir}/{}\"]\npub mod {};\n",
            m.path, m.module
        ));
    }
    for m in modules.iter().filter(|m| m.name.is_some()) {
        let name = &m.module;
        out.push_str(&format!(
            "fn __run_{name}<'a>(matches: &'a clap::ArgMatches, ctx: &'a mut CommandCtx) -> CommandFuture<'a> {{\n    Box::pin({name}::run(matches, ctx))\n}}\n"
        ));
    }
    out.push_str("/// Every command module that registers itself, in file-name order.\n");
    out.push_str("pub const COMMANDS: &[Registration] = &[\n");
    for m in modules.iter().filter(|m| m.name.is_some()) {
        out.push_str(&format!(
            "    Registration {{ name: {0}::NAME, command: {0}::command, run: __run_{0} }},\n",
            m.module
        ));
    }
    out.push_str("];\n");
    out
}

#[allow(dead_code)]
fn main() {
    let manifest = std::env::var("CARGO_MANIFEST_DIR").unwrap_or_else(|_| ".".into());
    let out_dir = std::env::var("OUT_DIR").unwrap_or_else(|_| ".".into());
    println!("cargo:rerun-if-changed=src/services");
    println!("cargo:rerun-if-changed=src/commands");
    println!("cargo:rerun-if-changed=src/main.rs");
    println!("cargo:rerun-if-changed=build.rs");
    let dir = Path::new(&manifest).join("src").join("services");
    let modules = match scan(&dir) {
        Ok(m) => m,
        Err(message) => {
            eprintln!("error: {message}");
            std::process::exit(1);
        }
    };
    let source = generate(&manifest, &modules);
    if let Err(e) = std::fs::write(Path::new(&out_dir).join("services_registry.rs"), source) {
        eprintln!("error: cannot write the services registry: {e}");
        std::process::exit(1);
    }
    let commands = match scan_commands(Path::new(&manifest)) {
        Ok(m) => m,
        Err(message) => {
            eprintln!("error: {message}");
            std::process::exit(1);
        }
    };
    let main_source = std::fs::read_to_string(Path::new(&manifest).join("src").join("main.rs"))
        .unwrap_or_default();
    if let Err(message) = check_command_names(&commands, &builtin_commands(&main_source)) {
        eprintln!("error: {message}");
        std::process::exit(1);
    }
    let source = generate_commands(&manifest, &commands);
    if let Err(e) = std::fs::write(Path::new(&out_dir).join("commands_registry.rs"), source) {
        eprintln!("error: cannot write the commands registry: {e}");
        std::process::exit(1);
    }
}
