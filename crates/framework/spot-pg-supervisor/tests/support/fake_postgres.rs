//! Test support program: behaves like `postgres`, `initdb` and `pg_ctl`, driven by its
//! own file name (or first argument) and environment variables. CI machines have no
//! PostgreSQL, so the supervisor's tests stage this binary as the "bundle".
//!
//! Behaviours (env):
//! - `FAKE_PORT`: port the postgres role binds (default 5433).
//! - `FAKE_LISTEN_DELAY_MS`: sleep before binding the port (readiness delay).
//! - `FAKE_EXIT_AFTER_MS` + `FAKE_EXIT_CODE`: crash (exit) that long after start.
//! - `FAKE_IGNORE_SIGINT=1`: ignore SIGINT (forces the supervisor's kill path).
//! - `FAKE_INITDB_FAIL=1`: initdb writes files but no `PG_VERSION`, exits 1.
//!
//! Staged copies named `postgres`, `initdb` or `pg_ctl` pick their role from the file
//! name; the bare `fake-postgres` binary takes the role as its first argument.

use std::io::Write;
use std::net::TcpListener;
use std::path::{Path, PathBuf};
use std::time::{Duration, Instant};

fn main() {
    let args: Vec<String> = std::env::args().collect();
    let role = detect_role(&args);
    let rest: Vec<String> = args.iter().skip(1).cloned().collect();
    match role.as_str() {
        "initdb" => run_initdb(&rest),
        "pg_ctl" => run_pg_ctl(&rest),
        "postgres" => run_postgres(&rest),
        other => {
            eprintln!("fake-postgres: unknown role {other:?}");
            std::process::exit(2);
        }
    }
}

/// Role from argv[0] basename (minus `.exe`) or the first argument.
fn detect_role(args: &[String]) -> String {
    if let Some(first) = args.get(1)
        && matches!(first.as_str(), "postgres" | "initdb" | "pg_ctl")
    {
        return first.clone();
    }
    let exe = args
        .first()
        .map(|path| {
            Path::new(path)
                .file_name()
                .map(|name| name.to_string_lossy().into_owned())
                .unwrap_or_default()
        })
        .unwrap_or_default();
    exe.trim_end_matches(".exe").to_string()
}

/// Finds the `-D <dir>` pair in the arguments.
fn data_dir_from(args: &[String]) -> Option<PathBuf> {
    args.iter()
        .position(|arg| arg == "-D")
        .and_then(|index| args.get(index + 1))
        .map(PathBuf::from)
}

/// initdb: create the marker files in the `-D` directory, unless told to fail.
fn run_initdb(args: &[String]) {
    let data_dir = data_dir_from(args).unwrap_or_else(std::env::temp_dir);
    // Record the full command line next to the data dir so tests can prove the
    // password never travelled as an argument.
    let _ = std::fs::write(data_dir.join("fake-initdb-argv.txt"), args.join("\u{1}"));
    if std::env::var("FAKE_INITDB_FAIL").is_ok() {
        // Simulate a crash mid-initialisation: files exist, `PG_VERSION` does not.
        let _ = std::fs::create_dir_all(data_dir.join("base"));
        let _ = std::fs::write(
            data_dir.join("base").join("template.db"),
            "half-written catalogue\n",
        );
        eprintln!("initdb: fake failure while writing the template catalogue");
        std::process::exit(1);
    }
    let _ = std::fs::create_dir_all(&data_dir);
    let markers = [
        ("PG_VERSION", "16\n"),
        ("postgresql.conf", "# generated by fake initdb\n"),
        ("postmaster.opts", "postgres -D <fake>\n"),
    ];
    for (name, contents) in markers {
        if let Err(error) = std::fs::write(data_dir.join(name), contents) {
            eprintln!("fake-postgres: could not write {name}: {error}");
            std::process::exit(1);
        }
    }
    println!("success. You can now start the database server (fake)");
    let _ = std::io::stdout().flush();
}

/// pg_ctl: only `stop` is implemented; the supervisor calls it on Windows paths.
fn run_pg_ctl(args: &[String]) {
    if args.iter().any(|arg| arg == "stop") {
        println!("pg_ctl: fake stop requested");
        let _ = std::io::stdout().flush();
    } else {
        eprintln!("fake-postgres: pg_ctl only implements stop");
        std::process::exit(1);
    }
}

/// postgres: write `postmaster.pid`, bind the port after the configured delay, crash
/// or ignore SIGINT as configured.
fn run_postgres(args: &[String]) {
    let data_dir = data_dir_from(args).unwrap_or_else(std::env::temp_dir);
    // Behaviours come from the process environment (child_env through the
    // supervisor) merged with the per-data-dir .env file, which wins. Edition 2024
    // forbids process-global mutation, so values are read into locals here.
    let file_values = read_env_file(&data_dir.join(".env"));
    let setting = |name: &str| {
        file_values
            .get(name)
            .cloned()
            .or_else(|| std::env::var(name).ok())
    };

    // Real postgres takes its port from PGPORT when started bare (the supervisor sets
    // it); the explicit FAKE_PORT remains as an override for direct experiments.
    let port: u16 = setting("PGPORT")
        .and_then(|value| value.parse().ok())
        .or_else(|| setting("FAKE_PORT").and_then(|value| value.parse().ok()))
        .unwrap_or(5433);

    #[cfg(unix)]
    if setting("FAKE_IGNORE_SIGINT").is_some() {
        // Sanctioned test-only block: ignore the shutdown request so the supervisor's
        // grace period elapses and the kill path is exercised.
        unsafe {
            libc::signal(libc::SIGINT, libc::SIG_IGN);
        }
    }

    write_pid_file(&data_dir, port);

    let listen_delay = setting("FAKE_LISTEN_DELAY_MS")
        .and_then(|value| value.parse::<u64>().ok())
        .map(Duration::from_millis)
        .unwrap_or(Duration::ZERO);
    let exit_after = setting("FAKE_EXIT_AFTER_MS")
        .and_then(|value| value.parse::<u64>().ok())
        .map(Duration::from_millis);
    let exit_code = setting("FAKE_EXIT_CODE")
        .and_then(|value| value.parse().ok())
        .unwrap_or(1);
    let started = Instant::now();
    if listen_delay > Duration::ZERO {
        std::thread::sleep(listen_delay);
    }
    let listener = match TcpListener::bind(("127.0.0.1", port)) {
        Ok(listener) => listener,
        Err(error) => {
            eprintln!("fake-postgres: could not bind 127.0.0.1:{port}: {error}");
            std::process::exit(1);
        }
    };
    println!("fake postgres listening on 127.0.0.1:{port}");
    let _ = std::io::stdout().flush();

    let _ = listener.set_nonblocking(true);
    loop {
        match listener.accept() {
            Ok(_) => {} // probe connections are answered by the accept itself
            Err(error) if error.kind() == std::io::ErrorKind::WouldBlock => {}
            Err(error) => {
                eprintln!("fake-postgres: accept failed: {error}");
                std::process::exit(1);
            }
        }
        if let Some(after) = exit_after
            && started.elapsed() >= after
        {
            let _ = std::fs::remove_file(data_dir.join("postmaster.pid"));
            std::process::exit(exit_code);
        }
        std::thread::sleep(Duration::from_millis(5));
    }
}

/// `KEY=VALUE` pairs from the per-run env file.
fn read_env_file(path: &std::path::Path) -> std::collections::HashMap<String, String> {
    let mut values = std::collections::HashMap::new();
    if let Ok(text) = std::fs::read_to_string(path) {
        for line in text.lines() {
            if let Some((key, value)) = line.split_once('=') {
                values.insert(key.trim().to_string(), value.trim().to_string());
            }
        }
    }
    values
}

fn write_pid_file(data_dir: &Path, port: u16) {
    let contents = format!("{}\n{}\n{port}\n\n", std::process::id(), data_dir.display());
    let _ = std::fs::create_dir_all(data_dir);
    if let Err(error) = std::fs::write(data_dir.join("postmaster.pid"), contents) {
        eprintln!("fake-postgres: could not write postmaster.pid: {error}");
        std::process::exit(1);
    }
}
