//! The ports a served operation group depends on, and the typed map that carries them.
//!
//! One file per port: `src/api/ports/<name>.rs` declares the port trait (object safe, async
//! through boxed futures like [`crate::api::FilesPort`]) and `pub const KEY: PortKey` for it.
//! `build.rs` turns the files into `pub mod` lines and the [`REGISTERED`] list, so adding a
//! port edits no shared file. A route group names the ports it needs in
//! `required_ports()`; the router mounts the group only when [`Ports`] holds all of them.

use std::any::TypeId;
use std::collections::HashMap;
use std::sync::Arc;

/// Names one port type: what a route group lists in `required_ports()`.
///
/// The key is the port's `dyn Trait` type. `PortKey::of` is a `const fn`: a group keeps its keys
/// in a `static` array (`static KEYS: [PortKey; 1] = [PortKey::of::<dyn FooPort>()];`) and
/// returns `&KEYS` from `required_ports()`.
#[derive(Clone, Copy)]
pub struct PortKey {
    name: fn() -> &'static str,
    id: fn() -> TypeId,
}

fn type_name_of<T: ?Sized>() -> &'static str {
    std::any::type_name::<T>()
}

fn type_id_of<T: ?Sized + Send + Sync + 'static>() -> TypeId {
    TypeId::of::<Arc<T>>()
}

impl PortKey {
    /// The key of the port type `T` (usually `dyn SomePort`).
    pub const fn of<T: ?Sized + Send + Sync + 'static>() -> PortKey {
        PortKey {
            name: type_name_of::<T>,
            id: type_id_of::<T>,
        }
    }

    /// The port type's name, for logs and operator listings (never a value).
    pub fn name(&self) -> &'static str {
        (self.name)()
    }

    fn id(&self) -> TypeId {
        (self.id)()
    }
}

impl std::fmt::Debug for PortKey {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        write!(f, "PortKey({})", self.name())
    }
}

impl PartialEq for PortKey {
    fn eq(&self, other: &Self) -> bool {
        self.id() == other.id()
    }
}

impl Eq for PortKey {}

#[derive(Clone)]
struct Entry {
    name: &'static str,
    value: Arc<dyn std::any::Any + Send + Sync>,
}

/// The ports one site provides, by type (`Arc<dyn Trait>`).
#[derive(Clone, Default)]
pub struct Ports {
    map: HashMap<TypeId, Entry>,
}

impl Ports {
    /// An empty map.
    pub fn new() -> Self {
        Self::default()
    }

    /// Provides `port`; a second port of the same type replaces the first (the last
    /// `with_*` call wins, as it always did).
    pub fn provide<T: ?Sized + Send + Sync + 'static>(&mut self, port: Arc<T>) {
        self.map.insert(
            TypeId::of::<Arc<T>>(),
            Entry {
                name: std::any::type_name::<T>(),
                value: Arc::new(port),
            },
        );
    }

    /// The port of type `T`, if provided.
    pub fn get<T: ?Sized + Send + Sync + 'static>(&self) -> Option<Arc<T>> {
        self.map
            .get(&TypeId::of::<Arc<T>>())
            .and_then(|e| e.value.downcast_ref::<Arc<T>>())
            .cloned()
    }

    /// Whether the port named by `key` is provided.
    pub fn has(&self, key: &PortKey) -> bool {
        self.map.contains_key(&key.id())
    }

    /// The first of `keys` that is not provided.
    pub fn first_missing(&self, keys: &[PortKey]) -> Option<PortKey> {
        keys.iter().find(|k| !self.has(k)).copied()
    }

    /// A map holding only the ports named by `keys` (all must be provided). A route group
    /// gets this, so a handler reaches its own declared ports and nothing else.
    pub fn subset(&self, keys: &[PortKey]) -> Result<Ports, PortKey> {
        let mut map = HashMap::new();
        for key in keys {
            match self.map.get(&key.id()) {
                Some(entry) => {
                    map.insert(key.id(), entry.clone());
                }
                None => return Err(*key),
            }
        }
        Ok(Ports { map })
    }

    /// The type names of the provided ports, sorted, for an operator listing.
    pub fn names(&self) -> Vec<&'static str> {
        let mut names: Vec<_> = self.map.values().map(|e| e.name).collect();
        names.sort_unstable();
        names
    }
}

impl std::fmt::Debug for Ports {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.debug_list().entries(self.names()).finish()
    }
}

