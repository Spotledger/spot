//! Local OS package mirror support: a manifest of package files and the generated metadata step.
//!
//! The air-gapped server cannot reach a distribution's repositories, so the packages travel on
//! media as plain files and the server builds its own repository metadata from them. This
//! module verifies the files — it never downloads anything. The metadata step itself is
//! distribution-specific (`createrepo_c` for RPM repositories, `apt-ftparchive` for Debian
//! ones), so it sits behind the [`MirrorBuilder`] trait and is executed through the
//! [`CommandRunner`] seam: the crate composes the command, a caller runs it.
//!
//! The repository layout the manifest describes:
//!
//! ```text
//! <repo>/packages/...    the package files, by manifest-relative path
//! <repo>/repodata/...    generated by the builder, not verified here
//! ```

use std::path::{Path, PathBuf};

use serde::Deserialize;
use spot_updater::Digest;

use crate::error::AirgapError;
use crate::manifest::is_safe_relative_path;
use crate::storage::{Storage, walk_files};

/// The `format` field of every mirror manifest.
pub const MIRROR_MANIFEST_FORMAT: &str = "spot-os-mirror";
/// The mirror manifest file name.
pub const MIRROR_MANIFEST: &str = "mirror.toml";
/// The directory the package files live under.
pub const MIRROR_PACKAGES_DIR: &str = "packages";

/// One package file the mirror manifest commits to.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct MirrorPackage {
    /// The file's path relative to the repository's `packages/` directory.
    pub path: String,
    /// The file's size in bytes.
    pub size: u64,
    /// The file's SHA-256.
    pub sha256: Digest,
}

/// The mirror manifest: the packages a local OS repository holds.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct MirrorManifest {
    /// The mirror's name.
    pub name: String,
    /// When it was generated (UTC seconds).
    pub generated_at: i64,
    /// Every package file, sorted by path.
    pub packages: Vec<MirrorPackage>,
}

/// The raw TOML shape of the mirror manifest.
#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct RawMirror {
    format: String,
    name: String,
    generated_at: i64,
    #[serde(default)]
    packages: Vec<RawPackage>,
}

#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct RawPackage {
    path: String,
    size: u64,
    sha256: String,
}

impl MirrorManifest {
    /// Parses a `mirror.toml`, checking every field and sorting the packages by path.
    ///
    /// # Errors
    /// [`AirgapError::MirrorMalformed`] when the TOML does not parse, an unknown field is
    /// present, the format is wrong, a path is unsafe, or a digest is malformed.
    pub fn from_toml(text: &str) -> Result<Self, AirgapError> {
        let raw: RawMirror =
            toml::from_str(text).map_err(|error| AirgapError::MirrorMalformed {
                detail: error.to_string(),
            })?;
        if raw.format != MIRROR_MANIFEST_FORMAT {
            return Err(AirgapError::MirrorMalformed {
                detail: format!(
                    "the format is `{}`, not `{MIRROR_MANIFEST_FORMAT}`",
                    raw.format
                ),
            });
        }
        let mut packages = raw
            .packages
            .into_iter()
            .map(|package| {
                if !is_safe_relative_path(&package.path) {
                    return Err(AirgapError::MirrorMalformed {
                        detail: format!("`{}` is not a safe relative path", package.path),
                    });
                }
                Ok(MirrorPackage {
                    path: package.path,
                    size: package.size,
                    sha256: Digest::from_hex(&package.sha256)?,
                })
            })
            .collect::<Result<Vec<_>, AirgapError>>()?;
        packages.sort_by(|a, b| a.path.cmp(&b.path));
        Ok(Self {
            name: raw.name,
            generated_at: raw.generated_at,
            packages,
        })
    }

    /// The manifest's TOML file form, packages sorted by path.
    #[must_use]
    pub fn to_toml(&self) -> String {
        #[derive(serde::Serialize)]
        struct PackageDoc<'a> {
            path: &'a str,
            size: u64,
            sha256: String,
        }
        #[derive(serde::Serialize)]
        struct MirrorDoc<'a> {
            format: &'a str,
            name: &'a str,
            generated_at: i64,
            packages: Vec<PackageDoc<'a>>,
        }
        let doc = MirrorDoc {
            format: MIRROR_MANIFEST_FORMAT,
            name: &self.name,
            generated_at: self.generated_at,
            packages: self
                .packages
                .iter()
                .map(|package| PackageDoc {
                    path: &package.path,
                    size: package.size,
                    sha256: package.sha256.to_hex(),
                })
                .collect(),
        };
        toml::to_string_pretty(&doc).unwrap_or_default()
    }

    /// The manifest entry for `path`, if it lists it.
    #[must_use]
    pub fn package(&self, path: &str) -> Option<&MirrorPackage> {
        self.packages.iter().find(|package| package.path == path)
    }
}

/// What a successful [`verify_mirror`] establishes.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct MirrorReport {
    /// The mirror's name.
    pub name: String,
    /// How many package files verified.
    pub packages: usize,
}

/// Verifies every package file in a local repository against its mirror manifest: each listed
/// file exists with the right size and SHA-256, and nothing unlisted is present.
///
/// # Errors
/// [`AirgapError::MirrorMissing`], [`AirgapError::MirrorDigestMismatch`],
/// [`AirgapError::MirrorExtra`] or [`AirgapError::Io`].
pub fn verify_mirror(
    storage: &dyn Storage,
    repo_root: &Path,
    manifest: &MirrorManifest,
) -> Result<MirrorReport, AirgapError> {
    let packages_dir = repo_root.join(MIRROR_PACKAGES_DIR);
    if storage.exists(&packages_dir)? {
        for path in walk_files(storage, &packages_dir)? {
            if manifest.package(&path).is_none() {
                return Err(AirgapError::MirrorExtra { path });
            }
        }
    }
    for package in &manifest.packages {
        let path = packages_dir.join(&package.path);
        if !storage.exists(&path)? {
            return Err(AirgapError::MirrorMissing {
                path: package.path.clone(),
            });
        }
        let bytes = storage.read(&path)?;
        if bytes.len() as u64 != package.size {
            return Err(AirgapError::MirrorDigestMismatch {
                path: package.path.clone(),
                expected: package.sha256.to_hex(),
                actual: Digest::of(&bytes).to_hex(),
            });
        }
        let digest = Digest::of(&bytes);
        if digest != package.sha256 {
            return Err(AirgapError::MirrorDigestMismatch {
                path: package.path.clone(),
                expected: package.sha256.to_hex(),
                actual: digest.to_hex(),
            });
        }
    }
    Ok(MirrorReport {
        name: manifest.name.clone(),
        packages: manifest.packages.len(),
    })
}

/// Composes the metadata-generation command for a distribution's repository tool.
pub trait MirrorBuilder {
    /// The builder's stable name, for logs.
    fn name(&self) -> &'static str;

    /// The command that regenerates the repository metadata for `repo_dir`: the program and its
    /// arguments, ready to run. An empty vector means the builder cannot serve this directory.
    fn metadata_command(&self, repo_dir: &Path) -> Vec<String>;
}

/// The `createrepo_c` builder for RPM (RHEL-compatible, Fedora) repositories.
#[derive(Debug, Default, Clone, Copy)]
pub struct CreaterepoC;

impl MirrorBuilder for CreaterepoC {
    fn name(&self) -> &'static str {
        "createrepo_c"
    }

    fn metadata_command(&self, repo_dir: &Path) -> Vec<String> {
        vec![
            "createrepo_c".to_owned(),
            "--database".to_owned(),
            repo_dir.display().to_string(),
        ]
    }
}

/// The `apt-ftparchive` builder for Debian (Ubuntu) repositories.
#[derive(Debug, Default, Clone, Copy)]
pub struct AptFtpArchive;

impl MirrorBuilder for AptFtpArchive {
    fn name(&self) -> &'static str {
        "apt-ftparchive"
    }

    fn metadata_command(&self, repo_dir: &Path) -> Vec<String> {
        vec![
            "apt-ftparchive".to_owned(),
            "packages".to_owned(),
            repo_dir.display().to_string(),
        ]
    }
}

/// Runs an external command. The metadata builders are executed through this seam, so a test
/// never shells out and a caller controls the environment.
pub trait CommandRunner {
    /// Runs `program` with `args`.
    ///
    /// # Errors
    /// [`AirgapError::MirrorBuilder`] when the command cannot be run or exits non-zero.
    fn run(&self, program: &str, args: &[String]) -> Result<(), AirgapError>;
}

/// Runs commands over `std::process::Command`, with no shell and no network.
#[derive(Debug, Default, Clone, Copy)]
pub struct StdCommandRunner;

impl CommandRunner for StdCommandRunner {
    fn run(&self, program: &str, args: &[String]) -> Result<(), AirgapError> {
        let status = std::process::Command::new(program)
            .args(args)
            .status()
            .map_err(|error| AirgapError::MirrorBuilder {
                detail: format!("{program}: {error}"),
            })?;
        if !status.success() {
            return Err(AirgapError::MirrorBuilder {
                detail: format!("{program} exited with {status}"),
            });
        }
        Ok(())
    }
}

/// Generates a repository's metadata through the builder's command.
///
/// # Errors
/// [`AirgapError::MirrorBuilder`] when the builder composes no command or the runner fails.
pub fn build_metadata(
    builder: &dyn MirrorBuilder,
    runner: &dyn CommandRunner,
    repo_dir: &Path,
) -> Result<(), AirgapError> {
    let command = builder.metadata_command(repo_dir);
    let (program, args) = command
        .split_first()
        .ok_or_else(|| AirgapError::MirrorBuilder {
            detail: format!("the {} builder composed no command", builder.name()),
        })?;
    runner.run(program, args)
}

/// The path of the packages directory of a repository.
#[must_use]
pub fn packages_dir(repo_root: &Path) -> PathBuf {
    repo_root.join(MIRROR_PACKAGES_DIR)
}
