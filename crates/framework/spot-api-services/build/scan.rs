//! The resource-file scanner. `build.rs` includes it, and `tests/scanner.rs` includes the same
//! file, so the tests exercise exactly the code the build runs.

#![allow(dead_code)]

/// True when `name` is a lower-case Rust module identifier.
pub fn is_module_name(name: &str) -> bool {
    let mut chars = name.chars();
    let Some(first) = chars.next() else {
        return false;
    };
    (first.is_ascii_lowercase() || first == '_')
        && chars.all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '_')
        && !matches!(
            name,
            "self" | "super" | "crate" | "mod" | "type" | "fn" | "use" | "pub"
        )
}

/// The module names for the given file names of `src/resources`: every `*.rs` except `mod.rs`,
/// in name order. A `*.rs` file whose stem is not a module identifier is an error naming it.
/// Names that do not end in `.rs` are ignored.
pub fn module_names(file_names: &[String]) -> Result<Vec<String>, String> {
    let mut modules = Vec::new();
    for file in file_names {
        let Some(stem) = file.strip_suffix(".rs") else {
            continue;
        };
        if stem == "mod" {
            continue;
        }
        if !is_module_name(stem) {
            return Err(format!(
                "src/resources/{file}: `{stem}` is not a module identifier (lower-case letters, digits and `_`, not starting with a digit)"
            ));
        }
        modules.push(stem.to_owned());
    }
    modules.sort();
    modules.dedup();
    Ok(modules)
}

/// The text of `resources_registry.rs`: one `#[path] pub mod` per module. `dir` is the absolute
/// `src/resources` directory with forward slashes (a `#[path]` inside an included file cannot
/// be relied on to resolve against the including file, so the path is absolute).
pub fn registry_source(dir: &str, modules: &[String]) -> String {
    let mut out = String::from("// Generated by build.rs from src/resources/*.rs. Do not edit.\n");
    for module in modules {
        out.push_str(&format!(
            "#[path = \"{dir}/{module}.rs\"]\npub mod {module};\n"
        ));
    }
    out
}
