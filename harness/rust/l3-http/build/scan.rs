//! The case-file scanner. `build.rs` includes it, and `tests/scanner.rs` includes the same file,
//! so the tests exercise exactly the code the build runs.

#![allow(dead_code)]

/// True when `name` is a lower-case Rust module identifier.
pub fn is_module_name(name: &str) -> bool {
    let mut chars = name.chars();
    let Some(first) = chars.next() else {
        return false;
    };
    (first.is_ascii_lowercase() || first == '_')
        && chars.all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '_')
        && !matches!(
            name,
            "self" | "super" | "crate" | "mod" | "type" | "fn" | "use" | "pub"
        )
}

/// True when some line of `text` starts (at column 0) with `prefix`.
fn declares(text: &str, prefix: &str) -> bool {
    text.lines().any(|line| line.starts_with(prefix))
}

const ORDER_DECL: &str = "pub const ORDER: u32";
const CASES_DECL: &str = "pub fn cases() -> Vec<CaseDef>";

/// The modules to register, in name order, from `(file name, file text)` pairs of
/// `src/cases`. A file registers when it declares both `pub const ORDER: u32` and
/// `pub fn cases() -> Vec<CaseDef>` at column 0. A file that declares only one of the two, or
/// that registers under a name that is not a module identifier, is an error naming the file. Any
/// other file (`mod.rs`, a helper module) is left alone.
pub fn registered(files: &[(String, String)]) -> Result<Vec<String>, String> {
    let mut modules = Vec::new();
    for (file, text) in files {
        let Some(stem) = file.strip_suffix(".rs") else {
            continue;
        };
        if stem == "mod" {
            continue;
        }
        match (declares(text, ORDER_DECL), declares(text, CASES_DECL)) {
            (false, false) => continue,
            (true, false) => {
                return Err(format!(
                    "src/cases/{file} declares `{ORDER_DECL}` but not `{CASES_DECL}`"
                ));
            }
            (false, true) => {
                return Err(format!(
                    "src/cases/{file} declares `{CASES_DECL}` but not `{ORDER_DECL}`"
                ));
            }
            (true, true) => {}
        }
        if !is_module_name(stem) {
            return Err(format!(
                "src/cases/{file}: `{stem}` is not a module identifier (lower-case letters, digits and `_`, not starting with a digit)"
            ));
        }
        modules.push(stem.to_owned());
    }
    modules.sort();
    modules.dedup();
    Ok(modules)
}

/// The text of `cases_registry.rs`: one `#[path] pub mod` per registered file and
/// `registered()`, the cases sorted by `(ORDER, name)`. `dir` is the absolute `src/cases`
/// directory with forward slashes (a `#[path]` inside an included file cannot be relied on to
/// resolve against the including file, so the path is absolute).
pub fn registry_source(dir: &str, modules: &[String]) -> String {
    let mut out = String::from("// Generated by build.rs from src/cases/*.rs. Do not edit.\n");
    for module in modules {
        out.push_str(&format!(
            "#[path = \"{dir}/{module}.rs\"]\npub mod {module};\n"
        ));
    }
    out.push_str(
        "\n/// Every registered case, ordered by `(ORDER, name)`.\npub fn registered() -> Vec<CaseDef> {\n    let mut all: Vec<(u32, CaseDef)> = Vec::new();\n",
    );
    for module in modules {
        out.push_str(&format!(
            "    all.extend({module}::cases().into_iter().map(|def| ({module}::ORDER, def)));\n"
        ));
    }
    out.push_str(
        "    all.sort_by(|a, b| (a.0, a.1.name).cmp(&(b.0, b.1.name)));\n    all.into_iter().map(|(_, def)| def).collect()\n}\n",
    );
    out
}
