//! The case index and `CASES.md`, generated from it.
//!
//! One index feeds the file: the `LEGACY` table (the cases that predate the registry, with the
//! owner and reason of the blocked ones taken from `LEGACY_BLOCKED`, the table the run reads) and
//! the registered [`CaseDef`]s. `cargo run -p l3-http -- --write-cases` writes `CASES.md`; a test
//! asserts the committed file equals the generated text, so a merge conflict in it is resolved by
//! regenerating, never by hand.

use std::collections::HashSet;
use std::fmt::Write as _;

use crate::cases::{CaseDef, CaseKind, LEGACY, LEGACY_BLOCKED, registered};

/// What a case is.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Kind {
    /// It runs.
    Case,
    /// The surface it needs is not served yet.
    Blocked {
        /// The task that owns the missing surface.
        owner: &'static str,
        /// What is missing.
        reason: &'static str,
    },
}

/// One case in the index.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Entry {
    /// The case's name.
    pub name: &'static str,
    /// The heading of `CASES.md` it is listed under.
    pub section: &'static str,
    /// What it pins, on one line.
    pub pins: &'static str,
    /// Case or blocked.
    pub kind: Kind,
}

impl Entry {
    fn from_def(def: &CaseDef) -> Self {
        Self {
            name: def.name,
            section: def.section,
            pins: def.pins,
            kind: match def.kind {
                CaseKind::Run(_) => Kind::Case,
                CaseKind::Blocked { owner, reason } => Kind::Blocked { owner, reason },
            },
        }
    }
}

/// Every case, in index order: the legacy rows, then the registered cases by `(ORDER, name)`.
pub fn entries() -> Vec<Entry> {
    let mut all: Vec<Entry> = LEGACY
        .iter()
        .map(|row| Entry {
            name: row.name,
            section: row.section,
            pins: row.pins,
            kind: match LEGACY_BLOCKED.iter().find(|(name, ..)| *name == row.name) {
                Some((_, owner, reason)) => Kind::Blocked { owner, reason },
                None => Kind::Case,
            },
        })
        .collect();
    all.extend(registered().iter().map(Entry::from_def));
    all
}

/// The first repeated case name, if any.
pub fn duplicate_name(entries: &[Entry]) -> Option<&'static str> {
    let mut seen = HashSet::new();
    entries
        .iter()
        .map(|entry| entry.name)
        .find(|name| !seen.insert(*name))
}

fn cell(text: &str) -> String {
    text.replace('|', "\\|")
}

/// The text of `CASES.md`.
pub fn cases_md() -> String {
    let entries = entries();
    let blocked = entries
        .iter()
        .filter(|entry| matches!(entry.kind, Kind::Blocked { .. }))
        .count();
    let mut sections: Vec<&str> = Vec::new();
    for entry in &entries {
        if !sections.contains(&entry.section) {
            sections.push(entry.section);
        }
    }
    let mut out = String::new();
    out.push_str(
        "<!-- Generated by `cargo run -p l3-http -- --write-cases`. Do not edit: change the case (or its `CaseDef`) and regenerate. -->\n\n",
    );
    out.push_str("# The cases this suite carries\n\n");
    out.push_str(
        "One behaviour per case, named like the L3 suite (`l3-documents`). A run prints one line\nper case; a **blocked** case names the work package that owns the missing surface, so the\ndistance between the brief and the product is visible in every run instead of being deleted.\nThe pass or fail state is not listed here: the run report carries it.\n\n",
    );
    let _ = writeln!(
        out,
        "{} cases, of which {} are blocked by surfaces the host does not serve yet.",
        entries.len(),
        blocked
    );
    for section in sections {
        let _ = write!(
            out,
            "\n## {section}\n\n| Case | Pins | Kind |\n| --- | --- | --- |\n"
        );
        for entry in entries.iter().filter(|entry| entry.section == section) {
            let kind = match &entry.kind {
                Kind::Case => "case".to_owned(),
                Kind::Blocked { owner, reason } => cell(&format!("blocked: {owner}: {reason}")),
            };
            let _ = writeln!(out, "| `{}` | {} | {kind} |", entry.name, cell(entry.pins));
        }
    }
    out
}
