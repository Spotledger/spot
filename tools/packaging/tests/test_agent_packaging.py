class SudoersTest(unittest.TestCase):
    def test_reference_output_is_accepted_and_lists_every_template(self):
        names = template_names()
        self.assertEqual(agent_sudoers.check(reference_dropin(names)), names)
        self.assertEqual(len(names), len(set(names)))

    def test_exactly_the_helper_run_name_forms_no_wildcard(self):
        text = reference_dropin(template_names())
        for line in text.splitlines():
            if line.lstrip().startswith("#"):
                continue
            for ch in "*?":
                self.assertNotIn(ch, line)
        self.assertNotIn("NOPASSWD: ALL", text)
        self.assertNotIn("ALL=(ALL)", text)

    def refused(self, text):
        with self.assertRaises(agent_sudoers.SudoersError):
            agent_sudoers.check(text)

    def test_refuses_wildcard_all_other_path_and_other_user(self):
        good = reference_dropin(["service.start"])
        self.refused(good.replace("run service.start", "run service.*"))
        self.refused(good.replace("run service.start", "run service.start *"))
        self.refused(good.replace(HELPER, "/usr/bin/systemctl"))
        self.refused(good.replace("NOPASSWD: SPOT_AGENT_PRIV", "NOPASSWD: ALL"))
        self.refused(good.replace("ALL=(root)", "ALL=(ALL)"))
        self.refused(good + "root ALL=(ALL) ALL\n")
        self.refused(good.replace("spot-agent ALL", "someone ALL"))
        self.refused(good.replace("!requiretty", "env_keep+=\"LD_PRELOAD\""))

    def test_blank_lines_and_comments_are_fine(self):
        agent_sudoers.check(reference_dropin(["service.start"]) + "\n# end\n")

    def test_refuses_duplicates_and_empty(self):
        self.refused(reference_dropin(["service.start", "service.start"]))
        self.refused("# nothing\n")

    def test_generate_runs_the_helper_and_checks_its_output(self):
        with tempfile.TemporaryDirectory() as tmp:
            good = Path(tmp) / "priv-good"
            out = Path(tmp) / "out.txt"
            out.write_text(reference_dropin(template_names()))
            good.write_text(f"#!/bin/sh\n[ \"$1 $2 $3\" = \"--print-sudoers --user spot-agent\" ] || exit 2\ncat '{out}'\n")
            good.chmod(0o755)
            self.assertEqual(agent_sudoers.generate(good), out.read_text())
            out.write_text(reference_dropin(["service.start"]).replace("run service.start", "run *"))
            with self.assertRaises(agent_sudoers.SudoersError):
                agent_sudoers.generate(good)
            with self.assertRaises(agent_sudoers.SudoersError):
                agent_sudoers.generate(Path(tmp) / "missing")

    def test_template_names_from_source(self):
        src = 'service!("service.start", "start", false),\n    Template {\n        name: "user.lock",\n'
        self.assertEqual(agent_sudoers.template_names_from_source(src), ["service.start", "user.lock"])

    @unittest.skipUnless(TEMPLATES_RS.is_file(), "WP-ADM-03.T2 source not in this tree")
    def test_sudoers_names_equal_the_helpers_template_table(self):
        names = agent_sudoers.template_names_from_source(TEMPLATES_RS.read_text())
        self.assertGreater(len(names), 0)
        self.assertEqual(sorted(agent_sudoers.check(reference_dropin(names))), sorted(names))

    @unittest.skipUnless(os.environ.get("SPOT_AGENT_PRIV"), "SPOT_AGENT_PRIV not set")
    def test_real_helper_output_is_accepted_and_equals_the_generated_one(self):
        helper = Path(os.environ["SPOT_AGENT_PRIV"])
        first = agent_sudoers.generate(helper)
        self.assertEqual(first, agent_sudoers.generate(helper))
        names = agent_sudoers.check(first)
        if TEMPLATES_RS.is_file():
            self.assertEqual(sorted(names), sorted(template_names()))
        self.assertEqual(first, reference_dropin(names))

    @unittest.skipUnless(subprocess.run(["which", "visudo"], capture_output=True).returncode == 0,
                         "visudo not found")
    def test_visudo_accepts_the_reference_dropin(self):
        with tempfile.TemporaryDirectory() as tmp:
            path = Path(tmp) / "spot-agent"
            path.write_text(reference_dropin(template_names()))
            path.chmod(0o440)
            run = subprocess.run(["visudo", "-cf", str(path)], capture_output=True, text=True)
        self.assertEqual(run.returncode, 0, run.stdout + run.stderr)


class SpecTest(unittest.TestCase):
    def setUp(self):
        self.spec = SPEC.read_text()

    def scriptlet(self, name):
        match = re.search(rf"(?ms)^%{name}\n(.*?)(?=^%[a-z]+\b|\Z)", self.spec)
        self.assertIsNotNone(match, name)
        return match.group(1)

    def test_no_scriptlet_starts_enables_or_enrols(self):
        for name in ("pre", "post", "preun", "postun"):
            body = "\n".join(l for l in self.scriptlet(name).splitlines() if not l.lstrip().startswith("#"))
            self.assertNotRegex(body, r"systemctl\s+(start|enable|restart)")
            self.assertNotRegex(body, r"spot-agent\s+enrol")
            self.assertNotRegex(body, r"(?i)token|key\b|secret|password")

    def test_upgrade_restarts_via_the_helper_and_keeps_state(self):
        self.assertIn("%systemd_postun_with_restart spot-agent.service", self.scriptlet("postun"))
        self.assertIn("%systemd_preun spot-agent.service", self.scriptlet("preun"))
        # the state directory is a %dir only: erasing the package never removes its content
        self.assertRegex(self.spec, r"%dir %attr\(0700,spot-agent,spot-agent\) %\{_localstatedir\}/lib/spot-agent")
        self.assertNotRegex(self.spec, r"%config\(noreplace\).*spot-agent\.toml")

    def test_downgrade_refused_in_pre(self):
        pre = self.scriptlet("pre")
        self.assertIn("rpm.vercmp", pre)
        self.assertIn("refusing to downgrade", pre)
        self.assertIn("exit 1", pre)

    def test_files_modes(self):
        self.assertRegex(self.spec, r"%attr\(0440,root,root\) %\{_sysconfdir\}/sudoers\.d/spot-agent")
        self.assertRegex(self.spec, r"%attr\(0755,root,root\) %\{_libexecdir\}/spot-agent/spot-agent-priv")
        self.assertIn("install -m 0440 %{SOURCE5} %{buildroot}%{_sysconfdir}/sudoers.d/spot-agent", self.spec)
        for line in self.spec.splitlines():
            m = re.search(r"install .*-m (0?[0-7]{3,4})\b", line)
            if m:
                self.assertFalse(int(m.group(1), 8) & 0o002, line)

    def test_sudoers_is_a_build_input_not_a_repo_file(self):
        self.assertIn("Source5:        spot-agent.sudoers", self.spec)
        self.assertEqual(list(AGENT.rglob("*sudoers*")).count(AGENT / "agent_sudoers.py"), 1)
        others = [p for p in AGENT.rglob("*") if p.is_file() and "sudoers" in p.name and p.suffix != ".py"]
        self.assertEqual(others, [], "the drop-in is generated at package build, not committed")

    def test_render_spec(self):
        text, version, release = build_agent.render_spec("2.0.0-rc.1", 1767225600)
        self.assertEqual((version, release), ("2.0.0", "0.rc.1"))
        self.assertNotIn("@", re.sub(r"%\{[^}]*\}", "", text.split("%changelog")[0]).replace("@VERSION@", ""))
        self.assertIn("Version:        2.0.0", text)

    def test_spec_comments_do_not_contain_macros(self):
        # rpm expands macros inside comment lines (see test_spec_comments.py).
        for line in self.spec.splitlines():
            if line.lstrip().startswith("#"):
                self.assertNotIn("%", line, line)


