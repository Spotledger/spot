HELPER = agent_sudoers.HELPER_PATH

#: The template names of WP-ADM-03.T2 (used when the source is not in the tree).
KNOWN_TEMPLATES = [
    "service.start", "service.stop", "service.restart", "service.reload",
    "service.enable", "service.disable", "service.mask", "service.unmask",
    "service.status", "user.lock", "user.unlock", "cert.install",
]

#: Ceiling of ``systemd-analyze security`` for the agent unit; the host unit's is 3.0.
SCORE_CEILING = 3.0


def reference_dropin(names, user="spot-agent"):
    """What the helper's generator prints (mirrors privilege/sudoers.rs)."""
    cmds = ", \\\n    ".join(f"{HELPER} run {n}" for n in names)
    return (
        "# Generated by `spot-agent-priv --print-sudoers`. Do not edit.\n"
        "# One exact command per privileged template; the parameters arrive on stdin.\n"
        f"Defaults:{user} !requiretty, !visiblepw\n"
        f"Cmnd_Alias SPOT_AGENT_PRIV = \\\n    {cmds}\n"
        f"{user} ALL=(root) NOPASSWD: SPOT_AGENT_PRIV\n"
    )


def template_names():
    if TEMPLATES_RS.is_file():
        names = agent_sudoers.template_names_from_source(TEMPLATES_RS.read_text())
        if names:
            return names
    return list(KNOWN_TEMPLATES)


def unit_directives(path=UNIT):
    """``{key: [values]}`` of the [Service] section (comments skipped)."""
    out = {}
    section = None
    for line in path.read_text().splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        if line.startswith("["):
            section = line
            continue
        if section == "[Service]" and "=" in line:
            key, value = line.split("=", 1)
            out.setdefault(key, []).append(value)
    return out


class UnitTest(unittest.TestCase):
    def setUp(self):
        self.d = unit_directives()

    def one(self, key):
        self.assertIn(key, self.d, key)
        self.assertEqual(len(self.d[key]), 1, key)
        return self.d[key][0]

    def test_unprivileged_account_and_private_state(self):
        self.assertEqual(self.one("User"), "spot-agent")
        self.assertEqual(self.one("StateDirectory"), "spot-agent")
        self.assertEqual(self.one("StateDirectoryMode"), "0700")
        self.assertEqual(self.one("UMask"), "0077")

    def test_sandbox(self):
        self.assertEqual(self.one("ProtectSystem"), "strict")
        for key in ("PrivateTmp", "PrivateDevices", "ProtectKernelTunables", "ProtectControlGroups",
                    "RestrictSUIDSGID", "LockPersonality", "RestrictNamespaces", "ProtectHome"):
            self.assertEqual(self.one(key), "true", key)

    def test_no_ambient_capabilities_and_no_new_privileges_off_by_design(self):
        # sudo is setuid: NoNewPrivileges=true would stop it. It is off, documented, and
        # the daemon itself gets no ambient capability.
        self.assertEqual(self.one("AmbientCapabilities"), "")
        self.assertEqual(self.one("NoNewPrivileges"), "false")
        text = UNIT.read_text()
        self.assertIn("sudo is a setuid program", text)

    def test_bounding_set_is_short_and_has_no_dangerous_capability(self):
        caps = self.one("CapabilityBoundingSet").split()
        self.assertTrue(caps and all(c.startswith("CAP_") for c in caps))
        for bad in ("CAP_SYS_ADMIN", "CAP_NET_ADMIN", "CAP_SYS_MODULE", "CAP_SYS_PTRACE", "CAP_SYS_RAWIO",
                    "CAP_SETFCAP", "CAP_MAC_ADMIN", "CAP_NET_RAW"):
            self.assertNotIn(bad, caps)
        self.assertLessEqual(len(caps), 8)

    def test_writable_paths_are_the_state_dir_and_the_cert_anchor_dir_only(self):
        paths = self.one("ReadWritePaths").split()
        self.assertEqual(paths, ["/var/lib/spot-agent", "-/etc/pki/ca-trust/source/anchors"])

    def test_exec_start_and_no_exec_pre_that_writes_secrets(self):
        self.assertEqual(self.one("ExecStart"),
                         "/usr/bin/spot-agent --state-dir /var/lib/spot-agent run")
        self.assertNotIn("ExecStartPre", self.d)
        self.assertEqual(self.one("Restart"), "on-failure")

    def test_unit_condition_means_not_enrolled_means_not_running(self):
        self.assertIn("ConditionPathExists=/var/lib/spot-agent/agent.key", UNIT.read_text())

    def test_not_wanted_state_is_not_enabled_by_the_package(self):
        # WantedBy exists so an operator can `systemctl enable`; nothing in the scripts does.
        self.assertIn("WantedBy=multi-user.target", UNIT.read_text())

    @unittest.skipUnless(subprocess.run(["which", "systemd-analyze"], capture_output=True).returncode == 0,
                         "systemd-analyze not found")
    def test_exposure_score_within_ceiling(self):
        with tempfile.TemporaryDirectory() as tmp:
            unit = Path(tmp) / "spot-agent.service"
            text = re.sub(r"(?m)^ExecStart=.*$", "ExecStart=/usr/bin/true", UNIT.read_text())
            unit.write_text(text)
            run = subprocess.run(["systemd-analyze", "security", "--offline=true", str(unit)],
                                 capture_output=True, text=True)
        match = re.search(r"exposure level for [^:]*: ([0-9.]+)", run.stdout + run.stderr)
        if match is None:
            self.skipTest("systemd-analyze security gave no score")
        self.assertLessEqual(float(match.group(1)), SCORE_CEILING)


