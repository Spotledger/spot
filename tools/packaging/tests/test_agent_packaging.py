#: Records every call; ``dpkg --compare-versions`` is answered with sort -V.
RECORDER = (
    "#!/bin/sh\n"
    "printf '%s' \"${0##*/}\" >> \"$SPOT_TEST_CALLS\"\n"
    "for arg in \"$@\"; do printf ' %s' \"$arg\" >> \"$SPOT_TEST_CALLS\"; done\n"
    "printf '\\n' >> \"$SPOT_TEST_CALLS\"\n"
    "exit 0\n"
)
DPKG = (
    "#!/bin/sh\n"
    "[ \"$1\" = --compare-versions ] || exit 0\n"
    "a=$2; op=$3; b=$4\n"
    "[ \"$a\" = \"$b\" ] && eq=1 || eq=0\n"
    "first=$(printf '%s\\n%s\\n' \"$a\" \"$b\" | sort -V | head -n 1)\n"
    "if [ \"$op\" = gt ]; then [ $eq = 0 ] && [ \"$first\" = \"$b\" ]; exit $?; fi\n"
    "exit 2\n"
)


class MaintainerScriptRunTest(unittest.TestCase):
    def setUp(self):
        self._tmp = tempfile.TemporaryDirectory(prefix="spot-agent-maint-")
        self.tmp = Path(self._tmp.name)
        self.stubs = self.tmp / "stub"
        self.stubs.mkdir()
        for name in ("systemctl", "systemd-sysusers", "systemd-tmpfiles"):
            self.stub(name, RECORDER)
        self.stub("dpkg", DPKG)
        self.calls = self.tmp / "calls"
        self.calls.write_text("")

    def tearDown(self):
        self._tmp.cleanup()

    def stub(self, name, text):
        path = self.stubs / name
        path.write_text(text)
        path.chmod(0o755)

    def run_script(self, name, args, text=None, systemd_running=True):
        text = text if text is not None else (DEBIAN / name).read_text()
        run_dir = self.tmp / "run-systemd" / "system"
        if systemd_running:
            run_dir.mkdir(parents=True, exist_ok=True)
        text = text.replace("/run/systemd/system", str(run_dir))
        script = self.tmp / name
        script.write_text(text)
        script.chmod(0o755)
        env = {"PATH": f"{self.stubs}:/usr/bin:/bin", "SPOT_TEST_CALLS": str(self.calls)}
        return subprocess.run(["/bin/sh", str(script), *args], capture_output=True, text=True, env=env)

    def calls_text(self):
        return self.calls.read_text()

    def test_first_install_creates_account_and_never_starts_anything(self):
        run = self.run_script("postinst", ["configure"])
        self.assertEqual(run.returncode, 0, run.stderr)
        text = self.calls_text()
        self.assertIn("systemd-sysusers spot-agent.conf", text)
        self.assertIn("systemd-tmpfiles --create spot-agent.conf", text)
        self.assertNotIn("systemctl", text)

    def test_upgrade_reloads_then_try_restarts_once(self):
        run = self.run_script("postinst", ["configure", "1.0.0-1"])
        self.assertEqual(run.returncode, 0, run.stderr)
        calls = [l for l in self.calls_text().splitlines() if l.startswith("systemctl")]
        self.assertEqual(calls, ["systemctl daemon-reload", "systemctl try-restart spot-agent.service"])

    def test_upgrade_without_systemd_does_not_call_systemctl(self):
        self.run_script("postinst", ["configure", "1.0.0-1"], systemd_running=False)
        self.assertNotIn("systemctl", self.calls_text())

    def test_preinst_refuses_a_downgrade_and_allows_upgrade_and_install(self):
        text = build_agent.render_preinst("1.2.0")
        self.assertNotIn("@DEB_VERSION@", text)
        refused = self.run_script("preinst", ["upgrade", "1.3.0"], text=text)
        self.assertEqual(refused.returncode, 1)
        self.assertIn("refusing to downgrade", refused.stderr)
        self.assertEqual(self.run_script("preinst", ["upgrade", "1.1.0"], text=text).returncode, 0)
        self.assertEqual(self.run_script("preinst", ["upgrade", "1.2.0"], text=text).returncode, 0)
        self.assertEqual(self.run_script("preinst", ["install"], text=text).returncode, 0)

    def test_remove_keeps_state_and_purge_deletes_only_the_literal_state_dir(self):
        text = (DEBIAN / "postrm").read_text()
        self.assertIn("rm -rf /var/lib/spot-agent\n", text)
        self.assertEqual(text.count("rm -rf"), 1)
        removed = self.tmp / "state"
        removed.mkdir()
        (removed / "agent.key").write_text("x")
        patched = text.replace("/var/lib/spot-agent", str(removed))
        self.assertEqual(self.run_script("postrm", ["remove"], text=patched).returncode, 0)
        self.assertTrue((removed / "agent.key").exists())
        self.assertEqual(self.run_script("postrm", ["purge"], text=patched).returncode, 0)
        self.assertFalse(removed.exists())


class BuildScriptTest(unittest.TestCase):
    def test_build_without_the_helper_binary_fails_clearly(self):
        with tempfile.TemporaryDirectory() as tmp:
            fake = Path(tmp) / "bin"
            fake.write_text("x")
            with self.assertRaises(SystemExit) as ctx:
                build_agent._inputs(fake, Path(tmp) / "missing")
            self.assertIn("helper binary not found", str(ctx.exception))

    def test_staged_inputs_use_the_generated_sudoers_with_mode_0440(self):
        with tempfile.TemporaryDirectory() as tmp:
            tmp = Path(tmp)
            (tmp / "agent").write_text("agent")
            helper = tmp / "priv"
            helper.write_text("#!/bin/sh\ncat <<'EOF'\n" + reference_dropin(template_names()) + "EOF\n")
            helper.chmod(0o755)
            sources = build_agent._inputs(tmp / "agent", helper)
        data, mode = sources["spot-agent.sudoers"]
        self.assertEqual(data.decode(), reference_dropin(template_names()))
        self.assertEqual(mode, 0o440)
        for name, (_, m) in sources.items():
            self.assertFalse(m & 0o002, name)

    def test_a_hand_edited_or_broad_dropin_stops_the_build(self):
        with tempfile.TemporaryDirectory() as tmp:
            tmp = Path(tmp)
            (tmp / "agent").write_text("agent")
            helper = tmp / "priv"
            helper.write_text("#!/bin/sh\necho 'spot-agent ALL=(ALL) NOPASSWD: ALL'\n")
            helper.chmod(0o755)
            with self.assertRaises(agent_sudoers.SudoersError):
                build_agent._inputs(tmp / "agent", helper)

    def test_no_file_in_the_agent_packaging_is_world_writable(self):
        for path in AGENT.rglob("*"):
            self.assertFalse(path.stat().st_mode & stat.S_IWOTH, path)

    def test_no_private_key_material_is_committed(self):
        for path in AGENT.rglob("*"):
            if path.is_file():
                self.assertNotIn("PRIVATE KEY", path.read_text(errors="ignore"), path)


