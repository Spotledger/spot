"""Ed25519 and canonical JSON, checked against bytes another implementation produced.

The point of these tests is that the build tool and the Rust signing crate agree on bytes. Checking
the tool against itself would prove nothing, so the vectors are the ones
``clients/avalonia/tests/Spotledger.Component.Host.Tests/Vectors/component-signing-vectors.json``
carries — generated by a program that links ``spot-bundle-signing``.
"""

from __future__ import annotations

import unittest

import support
from component_shell import canonical, ed25519

#: RFC 8032 section 7.1, test 1: an empty message.
RFC_SEED_1 = bytes.fromhex("9d61b19deffd5a60ba844af492ec2cc44449c5697b326919703bac031cae7f60")
RFC_KEY_1 = bytes.fromhex("d75a980182b10ab7d54bfed3c964073a0ee172f3daa62325af021a68f707511a")
RFC_SIGNATURE_1 = bytes.fromhex(
    "e5564300c360ac729086e2cc806e828a84877f1eb8e5d974d873e065224901555fb8821590a33bacc61e39701cf9b46bd25bf5f0595bbe24655141438e7a100b"
)

#: RFC 8032 section 7.1, test 2: a one-byte message.
RFC_SEED_2 = bytes.fromhex("4ccd089b28ff96da9db6c346ec114e0f5b8a319f35aba624da8cf6ed4fb8a6fb")
RFC_KEY_2 = bytes.fromhex("3d4017c3e843895a92b70aa74d1b7ebc9c982ccf2ec4968cc0cd55f12af4660c")
RFC_MESSAGE_2 = bytes.fromhex("72")
RFC_SIGNATURE_2 = bytes.fromhex(
    "92a009a9f0d4cab8720e820b5f642540a2b27b5416503f8fb3762223ebdb69da085ac1e43e15996e458f3613d0f11d8c387b2eaeb4302aeeb00d291612bb0c00"
)


class Ed25519Tests(unittest.TestCase):
    """The signature scheme, against the RFC's own vectors."""

    def test_rfc_8032_vector_one(self) -> None:
        self.assertEqual(RFC_KEY_1, ed25519.public_key(RFC_SEED_1))
        self.assertEqual(RFC_SIGNATURE_1, ed25519.sign(RFC_SEED_1, b""))
        self.assertTrue(ed25519.verify(RFC_KEY_1, b"", RFC_SIGNATURE_1))

    def test_rfc_8032_vector_two(self) -> None:
        self.assertEqual(RFC_KEY_2, ed25519.public_key(RFC_SEED_2))
        self.assertEqual(RFC_SIGNATURE_2, ed25519.sign(RFC_SEED_2, RFC_MESSAGE_2))
        self.assertTrue(ed25519.verify(RFC_KEY_2, RFC_MESSAGE_2, RFC_SIGNATURE_2))

    def test_a_changed_message_does_not_verify(self) -> None:
        self.assertFalse(ed25519.verify(RFC_KEY_2, b"\x73", RFC_SIGNATURE_2))

    def test_a_flipped_signature_bit_does_not_verify(self) -> None:
        broken = bytearray(RFC_SIGNATURE_2)
        broken[10] ^= 0x01
        self.assertFalse(ed25519.verify(RFC_KEY_2, RFC_MESSAGE_2, bytes(broken)))

    def test_malformed_shapes_are_false_and_not_an_exception(self) -> None:
        self.assertFalse(ed25519.verify(b"", b"", RFC_SIGNATURE_2))
        self.assertFalse(ed25519.verify(RFC_KEY_2, b"", b""))
        self.assertFalse(ed25519.verify(b"\x00" * 32, b"", RFC_SIGNATURE_2))

    def test_key_ids_are_the_ones_the_vectors_name(self) -> None:
        vectors = support.load_vectors()

        # The vectors were produced by the Rust crate; the same key has to give the same id here.
        for name in ("root", "publisher", "revoked", "outsider"):
            seed = bytes.fromhex(vectors["keys"][name]["seed_hex"])
            self.assertEqual(vectors["keys"][name]["key_id"], ed25519.key_id(ed25519.public_key(seed)), name)

    def test_an_unknown_seed_length_is_refused(self) -> None:
        with self.assertRaises(ValueError):
            ed25519.public_key(b"short")


class CanonicalJsonTests(unittest.TestCase):
    """The canonical encoding, against the bytes the Rust crate signed."""

    def test_the_plain_manifest_reproduces_the_signed_bytes(self) -> None:
        vectors = support.load_vectors()
        entry = vectors["manifests"]["plain"]

        encoded = canonical.signed_bytes(canonical.MANIFEST_DOMAIN, entry["body"])

        self.assertEqual(bytes.fromhex(entry["signed_bytes_hex"]), encoded)

    def test_the_awkward_string_manifest_reproduces_the_signed_bytes(self) -> None:
        vectors = support.load_vectors()
        entry = vectors["manifests"]["tricky_strings"]

        encoded = canonical.signed_bytes(canonical.MANIFEST_DOMAIN, entry["body"])

        self.assertEqual(bytes.fromhex(entry["signed_bytes_hex"]), encoded)

    def test_a_certificate_body_reproduces_its_own_bytes(self) -> None:
        vectors = support.load_vectors()
        body = vectors["certificate"]["body"]

        # The vector file shows the certificate's key as `public_key_b64` for readability; the signed
        # body names it `public_key`, so the field is renamed here and the bytes must then match.
        signed = {("public_key" if key == "public_key_b64" else key): value for key, value in body.items()}

        self.assertEqual(
            bytes.fromhex(vectors["certificate"]["signed_bytes_hex"]),
            canonical.signed_bytes(canonical.CERTIFICATE_DOMAIN, signed),
        )

    def test_the_revocation_list_reproduces_its_bytes(self) -> None:
        vectors = support.load_vectors()

        self.assertEqual(
            bytes.fromhex(vectors["revocation"]["signed_bytes_hex"]),
            canonical.signed_bytes(canonical.REVOCATION_DOMAIN, vectors["revocation"]["body"]),
        )

    def test_keys_are_sorted_and_whitespace_is_absent(self) -> None:
        self.assertEqual('{"a":1,"b":[true,false]}', canonical.encode({"b": [True, False], "a": 1}))

    def test_strings_are_escaped_the_way_serde_escapes_them(self) -> None:
        self.assertEqual('"a\\"b\\\\c\\n\\t\\u0001é"', canonical.encode('a"b\\c\n\t\x01é'))

    def test_a_float_is_refused_rather_than_rounded(self) -> None:
        with self.assertRaises(TypeError):
            canonical.encode({"amount": 1.5})

    def test_a_repeated_key_is_impossible_in_python_so_the_encoder_refuses_nothing_twice(self) -> None:
        # A dict cannot hold a key twice; what the encoder must refuse is a non-string or empty key.
        with self.assertRaises(ValueError):
            canonical.encode({"": 1})

    def test_an_empty_domain_is_refused(self) -> None:
        with self.assertRaises(ValueError):
            canonical.signed_bytes("", {"a": 1})


if __name__ == "__main__":
    unittest.main()
